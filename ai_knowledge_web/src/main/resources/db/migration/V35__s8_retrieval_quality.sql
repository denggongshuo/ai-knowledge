-- ---------------------------------------------------------------------------
-- ① `rerank_before_top1` —— 为什么必须**现在**加，而不是等有了数据再说
--
-- 需求 `08` §2.4 整节（「Rerank 效果验证」）的核心结论是
-- 「288ms 换来 **+18 个百分点**的 Top1 命中提升（63% → 81%）」，
-- 而旧表**没有任何"重排前"分数** ⇒ 那个结论**算不出来**。
--
-- ⚠️ 也不能靠子表 `sys_retrieval_trace_chunk` 事后补：`RetrievalService#toChunks`
-- 是把**融合池全部候选**按重排分重排**之后才**截 Top-K 的，而子表**只存截取后的 K 条**
-- ⇒ 融合池的 rank-1 **可能根本不在这 K 条里**，「已存子行的最大融合分」**不等于**
-- 重排前的 Top1。（核过代码，不是推测。）
--
-- 🔴 定这一列的依据是本仓既有硬约束 **`D-2`「打点后补 = 数据永久缺失」** ——
-- 与 `V22` 当初建整张打点表是同一条理由：**不确定的东西可以晚点算，
-- 但没记下来的东西永远算不出来**。
--
-- 【口径】存的是**重排分**，不是融合分 —— 这一点是这一列能不能用的关键：
--   · 「重排后 Top1」的口径是 `top1_score >= miss_threshold`；
--   · 若这一列存**融合分**（RRF 量级 ≈0.016），它与 `miss_threshold`(0.35)
--     **不同量纲** ⇒ 两侧命中率**没法比**，「净提升」就是个假数。
--   · 故取「**重排前名次第 1 的那条候选，在重排结果里拿到的分**」——
--     与重排后的分数**同一把尺**，差值才是真提升。
--
-- 【可空，且 NULL 有**两种**含义 —— 靠 `rerank_applied` 区分】
--   · `rerank_applied = 0` ⇒ 压根没重排（开关关了 / 没配模型 / 调用失败），
--     这一列**必然** NULL；此时 `top1_score` 也是融合分 ⇒ 两者都不参与命中率。
--   · `rerank_applied = 1` 但这一列 NULL ⇒ **重排前的那条候选没进重排结果的 top_n**
--     （重排客户端只返回 `top_n` 条，见 `RerankClient#rerank`）⇒ 它的重排分**未知**。
--     ⚠️ 这不是缺陷，是**覆盖率**：`rerank-effect` 端点必须把覆盖数**单独返回**，
--     否则「重排前命中率」是在一个**偏向高分的子集**上算的，而页面看不出来。
--
-- 不加索引：它只被窗口内的聚合扫描读到，不参与过滤（与 `top1_score` 同）。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_retrieval_trace
    ADD COLUMN rerank_before_top1 DECIMAL(12, 6) NULL
        COMMENT '重排前名次第 1 的候选在重排结果里拿到的分（与 top1_score 同一把尺，用于算净提升）。⚠️ 可空且有**两种** NULL：rerank_applied=0（没重排）或该候选未进重排 top_n（分未知，见端点返回的覆盖数）';


