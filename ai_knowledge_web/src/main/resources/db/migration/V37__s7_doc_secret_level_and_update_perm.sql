-- ===========================================================================
-- V37 · S7 · M06 阶段 B —— 文档级密级（`I-6` 的落地）+ 权限码 `doc:update`
--
-- 本迁移只有两件事：**给 `sys_document` 加一列**（NULL = 未覆盖）+ **一个新权限码**。
-- 没有新表、没有数据回填 —— 下面把"为什么不回填"单列一段（它是本迁移最要紧的决定）。
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- ① `sys_document.secret_level` —— 文档自己的密级，**NULL = 未覆盖（继承所属知识库）**
-- ---------------------------------------------------------------------------
-- 由来：不变量 `I-6`（《03》§5 的 `I-6`、《06》§2）：**文档密级只能提高，不能低于其所属
-- 知识库的密级**（否则用户可把机密文档降级绕过管控）。而在此之前**文档级密级根本不存在**：
--   · `sys_kb.secret_level` 在 `V9` 就加了（4 档 PUBLIC/INTERNAL/CONFIDENTIAL/SECRET）；
--   · 文档的"密级"一直**读的是所属库的**（`DocDetailService#meta` 投影的是 `k.secret_level`，
--     它的注释自己写着「I-6 的落地（文档级密级列）属 S7-M06-B ⇒ 当前生效密级 == 库级」）。
--
-- 🔴 **为什么用 `NULL` 表示"未覆盖"，而不是 `NOT NULL DEFAULT 'INTERNAL'` + 回填成库密级**：
--   在此之前，**没有任何一篇文档被单独设过密级** —— 它的密级从来就是"继承库的"。
--   `NULL` 是对这件事的**如实记录**；而"回填成库密级"等于**编造一次从未发生过的设置**，
--   并且会把"继承"与"用户主动设成与库相同"这两种情形**永久混在一起**
--   （需求 `06` §6.7 明确要求下拉标注「内部（**继承知识库**）」，让用户知道当前值来自哪里
--    —— 而那个标注只有在"未覆盖"可判定时才渲染得出来）。
--   ⇒ 于是本迁移**不做任何回填**。这与本仓 `D-2`（打点后补 = 数据永久缺失）是同一条纪律的
--   两个方向：**没有发生过的事，不要在数据里补一个看起来发生过值**。
--
-- 🔴 **生效密级 = max(文档密级, 库密级)**，且**这个 max 只在 Java 侧算**（`SecretLevel#within`
--   比序数），**检索侧的 SQL 里不排序数** —— 理由见下面 ② 的恒等式。
--
-- 列可空 ⇒ 实体 `SysDocument.secretLevel` 是 `SecretLevel`（可为 null），
--   读侧用 `coalesce` 语义时**不要在 SQL 里 `coalesce`**（见 ② 的最后一段）。
--
-- ⚠️ **不加索引**：过滤条件里 `secret_level` 只有 4 个取值（低基数），而同一 WHERE 里的
--   `kb_id in (...)` 与 `deleted_at is null` 已经把行集缩到很小 —— 给低基数列单独建索引
--   不会让优化器选它，只会多一份写入开销。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_document
    ADD COLUMN secret_level VARCHAR(16) NULL
        COMMENT '文档自己的密级：PUBLIC/INTERNAL/CONFIDENTIAL/SECRET；NULL = 未覆盖，生效值取 max(本列, sys_kb.secret_level)。I-6：只能提高，不能低于所属知识库';


-- ---------------------------------------------------------------------------
-- ② 检索侧怎么用这一列 —— **写在迁移里，因为它是"这一列为谁而加"的唯一说明**
-- ---------------------------------------------------------------------------
-- `RetrievalScope#visibleKbs` 里已经有库级那条：`k.secret_level in (:secretLevels)`，
-- 其中 `:secretLevels` 来自 `allowedSecretLevels(user)` —— **用户密级上限以内的等级名白名单**
-- （枚举全量筛一遍，不是"把上限转成 rank 再比大小"）。
--
-- 🔴 于是文档级只需在 `visibleDocIds` 里补**一个合取项**：
--
--       and (d.secret_level is null or d.secret_level in (:secretLevels))
--
--   它与库级那条的**合取**，**恰好等价于「max(文档, 库) ≤ 上限」**：
--     · max(d,k) ≤ 上限  ⟺  d ≤ 上限 **且** k ≤ 上限（纯序论恒等式，不需要知道 d、k 谁大）；
--     · 而 `:secretLevels` 就是"≤ 上限"那个**闭集**，所以两个 `in` 就是这两半；
--     · `d is null`（未覆盖）时生效值就是 k，而 k ≤ 上限已由库级那条保证。
--
-- ⚠️ **绝对不要**改用 SQL 的字符串比较来"取较大值"：
--   密级名按字母序是 `CONFIDENTIAL < INTERNAL < PUBLIC < SECRET`，与密级序
--   `PUBLIC < INTERNAL < CONFIDENTIAL < SECRET` **正好错位** ⇒
--   `greatest('INTERNAL','CONFIDENTIAL')` 会返回 `'INTERNAL'`。**把判断做反**的后果是
--   **有人看得见绝密**，而不是报错 —— 这类 bug 没有任何现象。
--   （若日后密级的可见集合不再是"≤ 上限"的闭集形状，才需要改成序数映射；
--     届时改一处：`RetrievalScope#allowedSecretLevels`。）
--
-- 🔴 **为什么不在 Milvus 的标量 `secret_level` 上再拦一遍**：那一列是**写入时的快照**
--   （`MilvusChunkWriter` 写的是 `VectorChunk#secretLevel()`，取自当时的所属库）。
--   按它过滤会让「提高密级」**必须重建索引才生效**，而需求 `06` §6.7 明写
--   「属性修改**后立即生效，无需重建索引**；移动知识库除外」。
--   `RetrievalScope` 的类注释里那条"不重复过滤"的理由仍然成立：**两处都判、口径一旦
--   不一致，就是"某批分片谁都搜不到"这种查不出原因的故障**。
--   该列继续保留（它是写入侧标量），但**检索时不读它**。
-- ---------------------------------------------------------------------------


-- ---------------------------------------------------------------------------
-- ③ 权限码 `doc:update` —— 「修改文档属性」（第 44 个码）
-- ---------------------------------------------------------------------------
-- 需求 `06` §6.7 把文档属性面板的三个可编辑项定为：**密级 / 所属知识库 / 内容标签**，
-- 对应 `PATCH /api/doc/{id}/attributes`，body `{ secretLevel, kbId, tags[] }`。
--
-- ⚠️ **口径空缺照实说**：需求 `05` §5 的权限矩阵里，文档域只有「上传 / 预览下载 /
--   删除重建索引」三行，**没有"修改属性 / 移动知识库"这个权限点**。于是本码是**推出来的**，
--   不是需求逐字要求的 —— 推断依据是既有码的射程：`doc:reindex`（同属"对某篇文档的写动作"）
--   授给了 `KB_ADMIN`，而"改属性"与它同族且更轻（它不改内容、不重算向量）。
--   ⇒ 已登记为一条待需求方确认的偏差，见 `plan/2026-09-20-S7-M06-B.md` §9。
--
-- 🔴 **本码只表达"能改文档属性"这一层；"能不能改**这一篇**"由服务层按库判**：
--   移动知识库要**同时**对源库（MANAGE）与目标库（`doc:upload`）有权限 ——
--   那是 `DataScopeService` / `KbGrantService` 的射程，**不能也不该**用权限码表达
--   （码是角色级的，而授权是逐库的）。这与 `doc:delete` / `doc:reindex` 的既有分工一致。
--
-- 授予：`KB_ADMIN`（"知识库管理 + 文档维护"，`V2:106`）。
--   ⚠️ **不给 `USER`** —— 普通用户只有"检索问答 + 个人会话"；也不给 `AUDITOR`
--   （它是只读合规视角）。`SUPER_ADMIN` 靠运行时 `*` 通配，不需要显式行。
-- 分组取「文档」（与 `doc:*` 同组）；sort 29 —— 该组现有 21~28，顺延。
-- ---------------------------------------------------------------------------
INSERT INTO sys_permission (code, label, group_name, sort)
VALUES ('doc:update', '修改文档属性', '文档', 29);

INSERT INTO sys_role_permission (role_id, permission_id, created_at)
SELECT r.id, p.id, NOW()
FROM sys_role r
         JOIN sys_permission p ON p.code = 'doc:update'
WHERE r.code = 'KB_ADMIN';
