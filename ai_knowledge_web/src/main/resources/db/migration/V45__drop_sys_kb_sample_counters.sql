-- V45 · 删除 `sys_kb` 的两个**示例计数列**（`doc_count` / `chunk_count`）
--       —— 2026-10-12 · `plan/2026-10-12-kb列表文档数归真.md`
--
-- 为什么删：这两列是 `V7` 建表时 seed 的**示例常量**（128 / 42 / 316 … 文档合计
--   1246；分片合计 38502），而**全仓没有任何代码写过它们** —— 建库那次写死 `0, 0`
--   （`KbService#create`）之后，上传 / 删除 / 重建 / 移库**一条都不更新**
--   （`setDocCount` 全仓零调用；唯一碰它们的曾是测试夹具手工 `+1`）。
--
--   于是它们既不是"事实"也不是"投影"，只是**冻在建库那一刻的假数**。读取它的地方
--   一律要回答一个永远不变的值：库下 0 篇文档时列表说「128 篇」，而库内文档列表
--   （`DocService#page`）回答 0 —— 用户在 2026-10-12 以「数据和真实情况对不上」
--   反馈的就是这个（W3 早在 `plan/2026-09-16-S4-M05-A.md` §1 登记过）。
--
-- 删之前**已把全部读取点改成现算**（同批，必须一起合）：新增
--   `service/KbCountReader` 作**唯一**计数口径（按 `sys_document` 未软删行现算），
--   五个消费方全部改道 —— 知识库列表 / 知识库设置页 / 重建影响预估 / 授权页 / 配额卡。
--   ⇒ 所以本迁移**不改变任何对外可见的数字语义**，只是拿掉那条没人维护的旧路。
--
-- ⚠️ **数据损失**：seed 的 1246 / 38502 会随之消失。那不是"删了真实数据" ——
--    `sys_document` 里本来就没有对应的行（`V12` 明确"本表不 seed 任何行"），
--    两个数从来只是 `V7` 的示例展示值。
--
-- ⚠️ **回滚**：要恢复得重加两列并**重新 seed**，而 seed 值已无从对齐
--    （`V7` 的常量是示例数据字典的抄本，不是真实统计）。
--
-- 为什么不选"给它补写侧"（上传 +1 / 删除 -1）：那要覆盖上传、删除、软删、恢复、
--   重建、移库**每一条**路径，漏一条就是新的静默漂移；现算没有这个问题，
--   而且库数量级很小，多一次聚合查询可以忽略。
-- ===========================================================================

ALTER TABLE sys_kb
    DROP COLUMN doc_count;

ALTER TABLE sys_kb
    DROP COLUMN chunk_count;
