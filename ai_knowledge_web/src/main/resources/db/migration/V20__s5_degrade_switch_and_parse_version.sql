-- ---------------------------------------------------------------------------
-- (1) `T-709`：重建索引期间降级为关键词检索的**全局开关**
--
-- 需求《11》§2.1 把「重建索引期间的服务状态」做成一个二选一：
--   ● 降级为关键词检索（推荐，问答仍可用但精度下降）
--   ○ 暂停问答服务（重建更快，但用户完全无法提问）
-- 那个二选一的对话框属 S6 的 `T-906`（换嵌入模型），本行是**全站默认**。
--
-- 默认 true = 选"降级"那一侧。理由：重建期走向量路会读到**正在换代的索引**
-- （旧代、或新代里写了一半的内容），而降级后至少给出的东西是对的 ——
-- 这与本项目「宁可少给、不可给错」的一贯取舍一致。
--
-- ⚠️ 新增本键**必须同时**改 `SystemSettings`（常量）与 `SystemSettingService.KEYS`
-- （查询范围）。只改一处的话现象是"配置改了但没人读"，而 `S5-M07-B` 刚查出过一次
-- 同形状的缺陷：`retrieval.rerank-top-k` 被 `KEYS` 查了、却没有任何调用方读它。
-- ---------------------------------------------------------------------------
-- ⚠️ 这里**不要**用 `||` 拼字符串：MySQL 默认 sql_mode 下 `||` 是逻辑或，不是拼接，
-- 会报 `22001 Truncated incorrect DOUBLE value`（本文件的第一次执行就是这么失败的）。
-- 要拼就用 `CONCAT(...)`；这里直接写成一整条字面量。
INSERT INTO sys_setting (setting_key, setting_value, value_type, group_name, label, description, editable, updated_at)
VALUES ('retrieval.degrade-during-reindex', 'true', 'BOOLEAN', '检索', '重建期降级',
        '知识库重建索引期间，把它的检索降级为关键词（BM25）。重建期走向量路会读到正在换代的索引；降级后问答仍可用、只是精度下降（《11》§2.1「降级而非中断」）',
        1, NOW());

-- ---------------------------------------------------------------------------
-- (2) `T-O05` 步 4：`sys_document.parse_version` —— 这份解析产物"是谁产的"
--
-- O5 §2 的缺口原话：「`parse.json` **无版本信息**：产物是定名覆盖写
-- （`parsed/{kbId}/{docId}/parse.json`），既不知道是用哪个解析器版本产的，
-- 也不知道是哪个 `TextLayerGuard` 阈值判的。」
-- 后果不是"看不了"，而是**"改了解析器之后哪些文档需要重解析"只能靠猜**。
--
-- 值的来源是产物内的 `meta`（`parse.json` 的 `parserVersion` + `parserConfigHash`
-- + `guardVersion` + `cleaningVersion` 拼成），由 `DocParseService` 成功路径回填。
-- **与 `parse_path` 并列**（O5 §4 步 4 的原话），不合并成一个字段：
-- 一个是"产物在哪"，一个是"产物是谁产的"，混在一起就再也分不开。
--
-- NULL 的语义**必须写死**（本列可空，且现有文档全是 NULL）：
--   `parse_version IS NULL` = **版本未知**（本批之前的产物）。
--   它算作"需要重解析"，**不是**"已是最新"。
--   反过来的话，老文档永远不会被重解析，这一列就白加了 ——
--   而现象是"加了指纹、筛出来的却永远是空集"，看起来像"没有需要重解析的文档"。
--
-- 可逆：`DROP INDEX` + `DROP COLUMN` 即可，无需回填业务数据。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_document
    ADD COLUMN parse_version VARCHAR(64) NULL COMMENT '解析产物版本指纹（解析器/配置/守卫/清洗四合一）；NULL = 本批之前的产物，视为版本未知，需重解析';

-- 索引是给"按版本差异筛出需重解析的文档"用的（O5 §4 步 5）。
-- 不建唯一约束：同一版本必然对应**多个**文档。
CREATE INDEX idx_doc_pver ON sys_document (parse_version);
