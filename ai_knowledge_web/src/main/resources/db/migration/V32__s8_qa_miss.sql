-- ===========================================================================
-- V32 · S8-M10-A（`T-A00`）· 未命中问题清单
--
-- 需求 `08-需求-运营分析.md` §1.2「未命中问题清单」+ §1.3 状态机 + §1.4 闭环第 1 步
-- （「召回分低于阈值**自动入池**，无需人工发现」）。
--
-- ---------------------------------------------------------------------------
-- 为什么要有这张表 —— `sys_retrieval_trace.miss_flag` 不是它
-- ---------------------------------------------------------------------------
-- 打点表记的是**每一次提问**（一行一次），而需求 §1.2 要的是
-- 「**同一语义问题的聚合次数**，用于排优先级（**不是把每次提问当成一行**）」，
-- 且要挂一个**状态机**（`PENDING/IN_LIST/RESOLVED/IGNORED` + 忽略人）。
-- 打点是**只增不改**的证据流，状态是**可变的意图** —— 两类东西混一张表，
-- 会让"重新沉淀一次"覆盖掉人工的处置结果。
-- `NoticeService` 的 javadoc 早就写明了这一点：「`miss_flag` 只是原始标记，
-- 不是"已沉淀为清单"」。
--
-- ---------------------------------------------------------------------------
-- 聚合键 = 归一化问句（**没有阈值**）
-- ---------------------------------------------------------------------------
-- 需求 §1.9 把「语义聚合能力」列为数据前置依赖，排期风险表 `R-6` 也标着
-- 「实现未定」。本批（用户 2026-09-20 裁定）走的是需求给的**退化方案里确定的那一半**：
--   `miss_key` = NFKC 归一化 → 去标点/符号/空白 → 小写 → SHA-256
-- **纯函数、零阈值、可机器对账**（池子 `sum(ask_count)` 必须等于 `miss_flag=1` 的行数）。
-- 「不同措辞但同一语义」的合并**没做** —— 阈值在真实问法语料出现前量不出来，
-- 而本仓已经在「没有语料就定阈值」上反复吃过亏（`T-O03` 的三个阈值至今卡着）。
-- ⚠️ 换语义聚类时**只改 `MissKeyNormalizer` 一处**，本表结构不动（键仍是字符串）。
--
-- ---------------------------------------------------------------------------
-- 为什么归属列叫 `last_user_id` 而不是 `user_id`
-- ---------------------------------------------------------------------------
-- 它是**聚合行**：一行可能对应好几个提问人，`last_user_id` 只是"最近提问的那位"。
-- 叫 `user_id` 会让人以为这一行属于某个人 —— 那是**用一个名字撒谎**。
-- ⚠️ 但代价要写下来：覆盖率闸扫的是**列名精确等于** `user_id` 的表 ⇒
-- **闸扫不到本表**。所以本表是**手工登记**进两侧登记表的，不是被闸逼出来的。
-- 这正是 `V31` 头注警告的那个形状（换个列名就能躲开闸）—— 这里没有躲的意思：
-- 登记是主动的，且两侧都写明了怎么清。**同一个形状另见 `S6-M11` §9 的登记**。
--
-- ---------------------------------------------------------------------------
-- 为什么排序规则是 `utf8mb4_0900_ai_ci`
-- ---------------------------------------------------------------------------
-- 它不是库默认（库默认是 `utf8mb4_unicode_ci`，见 `docker-compose.yml:50`），
-- 而是本批 `V33__collation_converge.sql` 的**收敛目标**：全仓 28 张表里
-- 18 张是 `0900_ai_ci`、10 张是 `unicode_ci`，跨表比字符串会报
-- `1267 Illegal mix of collations`（`S6-M11` 的第一条用例当场炸过）。
-- **新表直接写目标值**，免得 V33 之后还要再转它一次。
--
-- ---------------------------------------------------------------------------
-- 为什么没有种子数据
-- ---------------------------------------------------------------------------
-- 需求 §1 里那些数（108 / 1284 / 23）是**原型演示值**。而「未命中率」是这一页的
-- **核心健康度指标**（§1.1）—— 往里塞演示行，等于把一个健康度指标做成假的。
-- 池子的每一行都必须是**真提问沉淀出来的**。
--
-- 可逆：新建表 + 两个权限码，`DROP TABLE` / 删两行即可（有真实数据后不可逆）。
-- 迁移文件编号依现有最大编号递增：V31 → **V32**。
-- ===========================================================================

CREATE TABLE sys_qa_miss
(
    id             BIGINT         NOT NULL AUTO_INCREMENT,

    -- ---------- 聚合键（唯一）----------
    miss_key       VARCHAR(64)    NOT NULL COMMENT '归一化问句的 SHA-256 十六进制（`MissKeyNormalizer`）。**聚合键**：同一问法重复提问只累加，不新增行',

    -- ---------- 展示（需求 §1.2 的列）----------
    question       VARCHAR(500)   NOT NULL COMMENT '**原样**记录的用户问法。需求 §1.2 明写「不要做归一化改写 —— 真实问法是校准 HyQ 的原始素材」。⚠️ 超长按 500 截断（键仍按全文算）',
    ask_count      INT            NOT NULL DEFAULT 1 COMMENT '同一语义问题的聚合次数（本批 = 同一归一化键的提问次数）。**这是排序依据**：默认按它降序',
    first_ask_at   DATETIME       NOT NULL COMMENT '首次提问时刻。**没有另建 created_at**：它的值就等于这个 —— 两个列记一件事就是漂移的开始',
    last_ask_at    DATETIME       NOT NULL COMMENT '最近提问时刻（需求 §1.2 的「最近提问」列）',
    last_user_id   BIGINT         NULL COMMENT '⚠️ **最近**提问人，不是归属人 —— 本表是聚合行，一行可能对应多个提问人。可空：打点时未登录（`V22` 说正常恒非空，但列本身允许）',
    max_top_score  DECIMAL(12, 6) NULL COMMENT '提问过的**最高**相似度（需求 §1.2 的「最高相似度」，补录后与 `score_after` 组成「补录前 → 补录后」）。⚠️ 取 max 而不是最后一次：一次都没过线才叫未命中，拿"最好那次"是**对系统更严格**的口径。可空：旧行 / 分数缺失',
    kb_ids         VARCHAR(512)   NOT NULL DEFAULT '' COMMENT '涉及的知识库 id，逗号拼接 —— **与 `sys_retrieval_trace.kb_ids` 同口径**（那张表的注释写明"只展示与粗筛，不做关联"）。⚠️ 因此「按库筛」只能 `FIND_IN_SET`，且**一行可能跨多库**，是近似而非精确关联',

    -- ---------- 状态机（需求 §1.3）----------
    status         VARCHAR(16)    NOT NULL DEFAULT 'PENDING' COMMENT '状态机：PENDING / IN_LIST / RESOLVED / IGNORED。取值域 = `MissStatus` 枚举（与前端 `types/index.ts` 的 `MissStatus` 同名同值）',
    ignored_by     BIGINT         NULL COMMENT '忽略人（需求 §1.3：「「已忽略」记录**忽略人** —— 避免同一问题被反复忽略又反复冒出」）。仅 IGNORED 时非空',
    ignored_at     DATETIME       NULL COMMENT '忽略时刻',
    resolved_at    DATETIME       NULL COMMENT '标记已解决时刻。⚠️ 本批由**人工**触发；「分数达标自动关闭」要靠重放验证（`T-A01`），本批不做',

    -- ---------- 闭环证据（补录后）----------
    score_after    DECIMAL(12, 6) NULL COMMENT '补录并重建后重放得到的相似度。可空 = **还没重放过**（不是"重放后是 0"）。与 `max_top_score` 组成闭环证据（需求 §1.2：「补录后显示 补录前 → 补录后」）',

    updated_at     DATETIME       NOT NULL COMMENT '最近一次**改动本行**的时刻（状态变更 / 再次提问），不等于 last_ask_at',

    PRIMARY KEY (id),
    -- 幂等沉淀靠它：`on duplicate key update ask_count = ask_count + 1`
    UNIQUE KEY uk_qm_key (miss_key),
    -- 列表默认视图：按状态筛 + 按提问次数降序（需求 §1.2「默认按提问次数降序」）
    KEY idx_qm_status (status, ask_count),
    -- 时间窗（近 7 天 / 近 30 天）与「最近提问」排序
    KEY idx_qm_last (last_ask_at)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT ='未命中问题清单（T-A00）：聚合行 + 状态机；需求 08 §1.2/§1.3';

-- ---------------------------------------------------------------------------
-- 权限码：问答运营（`G8-9`「仅管理员可见」的落地）
-- ---------------------------------------------------------------------------
-- 为什么**新增**两个码，而不是复用现成的 `qa:feedback`：
--   `qa:feedback`（处理问答反馈）说的是"点踩/点赞那些反馈"，与本页的"没答上来的问题"
--   是**两个不同的岗**；压成一个码，将来要拆就得动所有已授予的角色。
--
-- 为什么**拆读/写两个码**：审计员（AUDITOR）的定位是"能看不能改"。
--   拆开之后 `G8-9` 才有**可证伪**的边界：同一个 AUDITOR token，
--   `GET /ops/qa/misses` 200 而 `PATCH` 403 —— 而不是"它俩一起 403，看不出哪个是对的"。
--   ⚠️ 承 `#168`/`#153` 的教训：**没有角色被授予的权限码 = 没有角色能证伪这条边界**。
--
-- 授予（实查 V2 的角色矩阵后定的）：
--   · `KB_ADMIN` 两个都给 —— 它是**唯一**同时有 `qa:feedback`+`doc:upload`+`doc:reindex` 的
--     角色，也就是唯一能走完「沉淀 → 补文档 → 重建索引 → 重放」整条闭环的人；
--   · `AUDITOR` 只给 view —— 只读，与它的 `audit:view` 同性质；
--   · `SUPER_ADMIN` 靠通配（`V2` 里那个 CROSS JOIN），无需单列；
--   · `USER`/`GUEST` 一个都没有 ⇒ 侧边栏角标与运营页对它们不可达。
--
-- 分组取「系统管理」（与 `audit:view`/`audit:export` 同组）：运营分析页与审计日志
-- 是同一类"全站视角的管理页"，而不是普通用户的问答功能。
-- sort 63/64 —— 该组现有 31~62，顺延。
-- ---------------------------------------------------------------------------
INSERT INTO sys_permission (code, label, group_name, sort)
VALUES ('ops:qa:view', '查看问答运营', '系统管理', 63),
       ('ops:qa:handle', '处置未命中问题', '系统管理', 64);

INSERT INTO sys_role_permission (role_id, permission_id, created_at)
SELECT r.id, p.id, NOW()
FROM sys_role r
         JOIN sys_permission p ON p.code IN ('ops:qa:view', 'ops:qa:handle')
WHERE r.code = 'KB_ADMIN';

INSERT INTO sys_role_permission (role_id, permission_id, created_at)
SELECT r.id, p.id, NOW()
FROM sys_role r
         JOIN sys_permission p ON p.code = 'ops:qa:view'
WHERE r.code = 'AUDITOR';
