-- ===========================================================================
-- S6 · 阶段 C2：图片块的三列元数据（`T-512` 步 8）
--
-- 需求出处 ——《06-需求-知识库与文档.md》第 159 行点名的四个元数据：
--   `object_key` / `pageNo` / `imageMd5` / `vlModelId`
-- 其中 `pageNo` 早就有列（`V14` 的 `page_no`），余下三个在本迁移补上。
--
-- ---------------------------------------------------------------------------
-- 为什么三列都挂在 sys_chunk 而不是新开一张表
-- ---------------------------------------------------------------------------
-- 一个图片块**就是**一行 `sys_chunk`（`chunk_type = 'IMAGE'`）——
-- 它的 `raw_content` 是「题注 + VL 描述」，进检索池靠的就是它。
-- 另开一张表就要在每一次回表、每一次向量化、每一次删除里 join 一次，
-- 而这三列**只对 IMAGE 块有意义**——正是"可空的、只对某类块有意义的列"，
-- 与 `parent_id`（只对表格子块）、`source_chunk_id`（只对 HyQ）同一个形态，
-- 本表已经有两个先例。
--
-- ---------------------------------------------------------------------------
-- 三列各自是什么、谁在消费
-- ---------------------------------------------------------------------------
--   · object_key  —— MinIO 上的原图对象名（`images/{kbId}/{docId}/{name}`）。
--                    消费方：检索回表取原图给人看（需求 06:167「原图存 MinIO 供人看」）。
--   · image_md5   —— 图片字节的 md5（服务端按字节算）。
--                    消费方：需求 06:160 的「按 imageMd5 去重」。
--                    ⚠️ **本批只落列，不做跨文档去重** —— 那个去重是**语料级**状态，
--                       与 `DocumentCleaner`「无状态纯函数」的设计直接冲突，
--                       需要单独裁定（已登记为遗留，见计划 §9 W4）。
--                       本批做的是**同篇内**去重（`DocumentImageDescriber` 步 5.1），
--                       它只影响"调不调 VL"，不写回这一列。
--   · vl_model_id —— 产出这条描述的 VL 模型标识。
--                    消费方：`T-908`（换 VL）——它要按这一列筛出"旧模型产的那些图"重算。
--                    ⚠️ **换模型后能按它筛**，而不是只能全库重建，这一列就是那个代价的分界。
--
-- ---------------------------------------------------------------------------
-- 可空性与回滚
-- ---------------------------------------------------------------------------
-- 三列**全部可空、无默认值**：非 IMAGE 块恒 NULL（本表绝大多数行）。
-- 现有查询按「`object_key IS NULL` ⇒ 非图片块」分支即可，**老数据一行都不用动**
-- （当前 `sys_chunk` 实测 0 行，本次也没有任何回填）。
--
-- ❌ **不加索引**：`image_md5` 的消费方（跨文档去重）本批**不做** ——
--    给一个还没有消费方的列建索引，是拿写入成本换一个不存在的查询。
--    真做去重的那一批再加（那时也能看清查询的真实形状）。
--    与 `V18` 对 `kind`/`disposition` 的处理同一条口径。
--
-- ✅ 可逆：`ALTER TABLE sys_chunk DROP COLUMN ...` 三列，无数据依赖。
--
-- ⚠️ 表名前缀 `sys_` 是既定约定（见 V22 头注释）。
-- ===========================================================================

ALTER TABLE sys_chunk
    ADD COLUMN object_key VARCHAR(255) NULL
        COMMENT '图片块的原图对象名（MinIO images/ 前缀）；非 IMAGE 块为 NULL',
    ADD COLUMN image_md5 CHAR(32) NULL
        COMMENT '图片字节 md5（服务端算）；本批只落列，跨文档去重未做',
    ADD COLUMN vl_model_id VARCHAR(64) NULL
        COMMENT '产出该图片描述的 VL 模型标识；T-908 换 VL 时按它筛旧模型产物';
