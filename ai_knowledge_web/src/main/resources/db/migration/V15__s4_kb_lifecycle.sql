-- ---------------------------------------------------------------------------
-- S4 · 阶段 D：sys_kb 生命周期两列（T-406 重建的切代落点 + T-407 软删）
--
-- 本批两件事各要一个持久化落点，且都必须落在 sys_kb 上：
--   · T-406 重建索引 = 按代 partition + 原子切换 → 切换点是"当前代"的持久记录
--   · T-407 删除知识库 = 软删进回收站（《03》§术语：保留 30 天）→ 必须有软删列
--
-- ---------------------------------------------------------------------------
-- 为什么是 index_generation，而不是给 Milvus 加一个 generation 标量字段
-- ---------------------------------------------------------------------------
-- 背景冲突（本批开工前查出的 BLOCKER，见 plan/2026-09-17-S4-D.md §1 的 #7）：
--   D-7 要求重建"写新 collection + 原子切换、不得原地删旧索引"；
--   而 D-4/R-8 定死了"单 collection"。
--   collection 是全库共用的，而 POST /kb/{id}/reindex 是**按一个库**重建 ——
--   整集合的原子切换做不了"只换 8 个库里的某一个"。
--
-- 裁定：单 collection + **按代 partition**（步 0 探针已实测分区隔离成立，5/5）。
--   分区名 = kb{kbId}_g{generation}。重建写新代分区 → 完成后**一次 UPDATE** 切代
--   → 检索侧只查当前代分区 → 旧代分区在切换前一个字节都没动，
--   所以 G3-5「中途 kill 旧索引仍可用」是**天然满足**的，不是额外做出来的。
--
-- 为什么"代"落在 MySQL 而不是 Milvus：
--   ① 切换点必须是**一次原子的、可回滚的**写。MySQL 的单行 UPDATE 是事务性的，
--      而 Milvus 没有跨分区的事务语义；
--   ② 若改成给 Milvus 加 generation 标量列，就会把可过滤字段从 4 个变成 5 个 ——
--      那要**推翻 2026-09-17 刚拍板的 G4-10 口径**（"标量字段只含
--      doc_id/kb_id/chunk_type/secret_level"），代价远大于收益；
--   ③ 检索侧本来就要先查 MySQL 算 doc_id 集合（I-9），读这一列**不增加往返**。
--
-- 为什么 DEFAULT 1 而不是 0：0 会让"首代"与"未初始化"两种状态撞在一起。
-- 从 1 开始，任何一行都有明确的"当前代"，且 8 个演示库无需回填。
--
-- ---------------------------------------------------------------------------
-- 为什么 deleted_at 用 NULL 而不是 status 加一个 DELETED 取值
-- ---------------------------------------------------------------------------
-- 与 V10 的 reindex_required 同一条理由，且更强：
--   status 描述的是"索引过程"（READY / INDEXING），"已删除"是**生命周期**、
--   与索引过程**正交** —— 一个库可以"正在索引时被删除"。并进 status 会让这个
--   组合无法表达，而且每一个读 status 的地方都要多一个"这个值算不算存在"的判断。
--   独立列是纯加法，不碰任何既有消费点。
--
-- 为什么 NULL = 未删：与 sys_user / sys_document 的软删口径一致（全站统一），
--   且 NULL 天然被 `where deleted_at is null` 收编，不需要额外约定哨兵值。
--   注意 sys_document.deleted_at 已是这个口径（V12），两处对齐。
--
-- 为什么 NOT NULL 的列一定要给 DEFAULT：sys_kb 已有 8 行演示数据，
--   加 NOT NULL 列不给默认值在严格模式下会失败；给了默认值则老行语义天然正确。
--
-- ---------------------------------------------------------------------------
-- 索引
-- ---------------------------------------------------------------------------
-- idx_kb_deleted：列表接口按"未删除"过滤是**最高频**的读路径。
--   V7 已有 idx_kb_dept（数据范围过滤）。量级是库数（8 → 千级），
--   按 V10 的同一条判断，这里其实也可以不加索引 —— 但软删是本批新增的
--   **每一处列表查询都要带**的条件（不像 reindex_required 只在特定页面用），
--   加一个单列索引成本极低而收益明确，故加。
--
-- ⚠️ 跑过的迁移**只增不改**：V1~V14 一行不动，本次改动全部落在这里。
-- ---------------------------------------------------------------------------

ALTER TABLE sys_kb
    ADD COLUMN deleted_at DATETIME NULL
        COMMENT '软删时间（NULL = 未删）。删除知识库进回收站，保留 30 天后可彻底清除（T-616）',
    ADD COLUMN index_generation INT NOT NULL DEFAULT 1
        COMMENT '当前向量所在的分区代（Milvus 分区名 = kb{kbId}_g{index_generation}）。重建写新代、完成后一次 UPDATE 切代；D-7 的原子切换点',
    ADD KEY idx_kb_deleted (deleted_at);
