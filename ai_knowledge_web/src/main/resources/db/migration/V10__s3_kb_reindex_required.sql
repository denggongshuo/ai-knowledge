-- S3 · 阶段 B2：sys_kb 补「待重建」标记（T-404 保存配置的状态落点）
--
-- 为什么需要这一列：
--   G3-3 的判据是「保存后返回 needReindex=true；**未重建前检索行为不变**」。
--   "改配置不自动生效"这件事必须有**持久化的落点**，否则：
--     · 页面刷新后无法告诉用户"这个库改了配置但还没重建"；
--     · S4 的 T-406 重建索引没有"哪些库需要重建"的筛选依据，只能全库重跑。
--   所以它不是 T-404 的返回值缓存，而是**跨批的状态契约**（B2 写、S4 清）。
--
-- 为什么用新列而**不并入 sys_kb.status 的词表**：
--   status 的取值是域内真值 READY / INDEXING（V7 建表口径）。往里加第三态
--   （如 REINDEX_REQUIRED）会让"索引正在进行"与"配置脏了等重建"混在同一列 ——
--   前者是**过程**、后者是**条件**，两者可以同时成立（正在索引，且又改了一次配置）。
--   且 B1 已经因为 status 的词表分叉吃过一次亏（W1 / 《10》§14.2-2 登记在案），
--   再扩一次词表等于把那个坑挖深。用独立的布尔列是**纯加法**，不碰任何既有消费点。
--
-- 为什么 NOT NULL DEFAULT 0：
--   ① 8 个演示库无需回填 —— 它们从未改过配置，语义上就是"不需要重建"；
--   ② 读侧可以按 boolean 收，不必处理 null 三态（NULL 会让每个消费点都要决定
--      "null 算需要还是不需要"，那是最容易各写各的地方）。
--
-- 不加索引：本批唯一按它筛选的场景是"列出待重建的库"，量级是**库数**（8 → 千级），
--   全表扫描足够。等 S4 的 T-406 真有高频轮询再按需加。
--
-- ⚠️ 跑过的迁移**只增不改**：V1~V9 一行不动，本次改动全部落在这里。
-- ---------------------------------------------------------------------------

ALTER TABLE sys_kb
    ADD COLUMN reindex_required TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '配置已改、索引未重建（T-404 置 1，S4 的 T-406 重建完成后置 0）。刻意独立于 status，不扩 status 词表';
