-- ===========================================================================
-- S5 · 阶段 B：HyQ（假设问题）块回指源块（`T-507` 的挂起半边）
--
-- 为什么要加这一列 —— `汇总.md` §4-271 挂了很久的那个判据
-- ---------------------------------------------------------------------------
-- `D-5` §1.6 把 HyQ 定为**分片级**产物（n 次调用 / 篇），但**没给 HyQ 块任何
-- 回指源块的字段**；而 `G4-6` 的 SQL 断言（`S4-M05-C1` 已收口）要求
-- 「凡有 `parent_id` 的块，父块必须是 `TABLE`」—— 于是"把 HyQ 挂到源块下面"
-- 这条**最自然的路是封死的**。
-- 后果不是"少个字段"，而是一个**答不出来的问题**：检索命中一条 HyQ 块之后，
-- **拿什么给大模型？** 那条 HyQ 是"假设的问句"（如「A-100 的单价是多少」），
-- 它自己不含答案 —— 把问句原样喂给模型，模型只能看到一个孤零零的提问。
-- 这正是 §4-271 原话说的「只能在有检索实现时回答」。
--
-- 本列就是那个答案：命中 HyQ 块时按它取**源块正文**喂给模型，
-- 而问句只用于**召回**（它的存在意义就是匹配用户的另一种问法）。
--
-- ---------------------------------------------------------------------------
-- 为什么是 `source_chunk_id` 而不是复用 `parent_id`
-- ---------------------------------------------------------------------------
-- 见上：复用会当场把 `G4-6` 的断言打成红的（子块指向非 TABLE 父块）。
-- 两个字段语义不同 —— `parent_id` 是**结构上的父子**（表格行属于表格），
-- `source_chunk_id` 是**生成上的来源**（这条问句是从哪段正文推出来的）。
-- 合并它们等于说"表格行与 HyQ 是同一回事"。
--
-- ---------------------------------------------------------------------------
-- 可空性与回滚
-- ---------------------------------------------------------------------------
-- 可空、无默认值：**只有 HyQ 块**有值，其余 8 种块类型一律 NULL。
-- 既有行（当前 `sys_chunk` 实测 0 行）不需要回填。
-- 读侧口径：`source_chunk_id IS NULL` 一律按"普通块"处理，**不报错**。
-- ⚠️ 检索侧必须容忍**悬空**（源块被重解析换掉后 id 不存在）—— 那时降级为
-- 「只喂 HyQ 自身文本」并留痕，绝不能抛异常：那会炸掉整个检索请求，
-- 而不是少几条结果（与 `S4-D` 的"查不存在的分区会报错"同一条纪律）。
--
-- 不加外键约束（与本表既有的 `parent_id` 一致）；加索引是因为检索侧要按它回查。
-- 可逆：`DROP INDEX` + `DROP COLUMN` 即可。
--
-- ⚠️ 表名前缀 `sys_` 是既定约定（见 V22 头注释）。
-- ===========================================================================

ALTER TABLE sys_chunk
    ADD COLUMN source_chunk_id BIGINT NULL
        COMMENT 'HyQ 块的来源块 id —— 命中后按它取源块正文喂模型（问句只用于召回）。⚠️ 仅 HYPOTHESIS_QA 有值；悬空时降级不抛异常',
    ADD INDEX idx_chunk_source (source_chunk_id);