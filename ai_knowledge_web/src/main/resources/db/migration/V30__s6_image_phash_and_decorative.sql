-- ===========================================================================
-- S6 · 阶段 E：装饰图判定（`T-O03` 的挂起半边）
--
--   · image_phash    —— 这张图的**感知哈希**（dHash 64 位，十六进制）
--   · is_decorative  —— 这张图是否被判为**装饰图**（跨文档重复的 logo / 图标）
--
-- ✅ 可逆：DROP INDEX + DROP COLUMN 两列，无业务数据依赖。
--
-- ⚠️ **撤回时四件事一件不能少**（`S6-M05-D` §9-216 实测踩过）：
--    删源 + 删 `target/classes` 下那份副本 + 清 `flyway_schema_history` 那行 + 删列。
--    只删源文件的话，**下一轮跑批会把它原样再应用一遍**，而且测试**照样全绿**（静默）。
--
-- ---------------------------------------------------------------------------
-- 为什么现在才做 —— `V29` 把这件事"留给后来人"的那段原文
--
-- `V29` 加 `image_md5` 时写着：
--   「❌ **不加索引**：`image_md5` 的消费方（跨文档去重）本批**不做**」
-- 本批就是那个消费方落地的时候，所以 `idx_chunk_iphash` 这次**要加**
-- （对照 `V29` 明确不加 —— 当时加了是白占）。
--
-- ---------------------------------------------------------------------------
-- 🔴 为什么另加一列 `image_phash` 而不是复用 `image_md5`
--
-- md5 是**字节级**的。同一张 logo 在文档里被重编码过（换格式、换压缩参数、
-- 换个工具另存）字节就不同，md5 判不出"这还是那张图"。
-- 而"装饰图"这个问题的本质是**看起来是同一张图** —— `O3` §4 步 3 点名的是 pHash。
--
-- ⇒ 两列都留，各回答一个问题：
--     `image_md5`   —— 这两个是**同一个对象**吗（用于复用 VL 描述）
--     `image_phash` —— 这是**同一张图**吗（用于装饰图判定）
--
-- ---------------------------------------------------------------------------
-- 🔴 为什么 CHAR(16) 而不是 BIGINT
--
-- dHash 是 64 位，十六进制表示**定长 16 字符**。取 CHAR 与 `content_sha256`
-- （`CHAR(64)`）同一条理由：指纹类字段的**可读性**有价值 —— 用 SQL 手工核对时
-- 不必 `hex()` 包一层。存 BIGINT 省 8 字节，换来的是一次都读不懂。
--
-- 而且 LSH 分带（`ImageHash#bands`）是**按 4 字符一段**切这个字符串去取候选的 ——
-- 存 BIGINT 的话那一步要先在 SQL 里做位移与掩码，可读性再降一档。
--
-- ---------------------------------------------------------------------------
-- NULL 语义（**必须写下来**）
--
-- `V30` 之前入库的块、以及所有非 IMAGE 块，`image_phash` 均为 NULL。
-- **两侧都非空才比较**（照 `ContentFingerprint.same` 的口径）——
-- 把一批 NULL 当成"互相相同"会让所有旧图在跨文档计数里互相命中。
--
-- `is_decorative` 反过来是 NOT NULL DEFAULT 0：它是**判定结论**，
-- "没判过"与"判过、不是装饰图"在这条链上的下一步动作**相同**（都进召回池），
-- 压成一个值不会让人分不出该做什么 —— 与 `degraded` 那处必须保三态的情形不同。
--
-- ⚠️ 表名前缀 `sys_` 是既定约定（见 V22 头注释）。
-- ===========================================================================

ALTER TABLE sys_chunk
    ADD COLUMN image_phash CHAR(16) NULL
        COMMENT '图片感知哈希 dHash 64 位十六进制；非 IMAGE 块与 V30 前的旧块为 NULL',
    -- ⚠️ **`TINYINT(1)` 而不是裸 `TINYINT`** —— 这两个在 Hibernate 的
    -- `ddl-auto: validate` 下**是两种类型**：前者映射 boolean，后者映射 byte。
    -- 实测踩到（`S6-M05-D`）：写成裸 `TINYINT` 而实体声明 `Boolean`，启动当场失败
    -- (`found [tinyint], but expecting [bit]`)，整个 Spring 上下文起不来。
    -- `V19` 的 `is_boilerplate` 就是 `TINYINT(1)` —— 照它写，别自己发明。
    ADD COLUMN is_decorative TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '1 = 装饰图（跨文档重复的 logo/图标），不进向量召回池；0 = 正常';

-- 跨文档计数按 `image_phash` 分组查（`DocRecordWriter#markDecorativeImages`），
-- 与文本侧的 `idx_chunk_csha` 是同一形状。
CREATE INDEX idx_chunk_iphash ON sys_chunk (image_phash);
