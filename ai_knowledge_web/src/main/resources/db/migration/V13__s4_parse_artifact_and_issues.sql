-- ---------------------------------------------------------------------------
-- 1) sys_document 加一列：解析产物在对象存储里的对象名
--
-- 与 storage_path 同一条纪律：**存对象名不存 URL**（存事实不存视图 ——
-- 预签名 URL 会过期、换域名/换 CDN 时形态又变，存 URL 等于把"以后必须迁移全表数据"写进设计）。
--
-- 可空：只有解析**成功**才写。UPLOADED / PARSING / FAILED 三态均为 NULL。
-- 它与质量四列一起构成"解析真的跑过"的证据 —— 光看 status 分不清
-- "没开始解析" 与 "解析完但内容为空"。
-- 这里用 ALTER 而不是重建表：V12 已在多处环境跑过，重建会丢数据。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_document
    ADD COLUMN parse_path VARCHAR(512) NULL
        COMMENT '解析产物对象名（parsed/{kbId}/{docId}/parse.json）；仅解析成功时非空';

-- ---------------------------------------------------------------------------
-- 2) sys_parse_issue —— 逐页解析问题
--
-- 为什么必须单独一张表（而不是复用 sys_document.error_msg）：
--   error_msg 是**文档级**的一句话，回答"这篇为什么整体失败"；
--   而「未识别的表格」是**逐页**、且一篇文档可以有多处、原因各不相同的问题
--   （《06》§3.9 与 T-511 都点名要「文档 + 页码 + 原因」三个字段）。
--   把 N 条逐页问题塞进一个 VARCHAR(512) 是必然要丢信息的设计。
--
-- 为什么"失败"（FAILED）与"识别不到表格"（质量降级）都要进这张表：
--   07 §2.6 的原话是「让上传的人**当场**就知道」；T-0S1 §一的结论是
--   「真风险不在识别准不准，而在识别不到时静默返回空」。
--   扫描件整篇失败时，逐页的"这一页没有可复制文本"比一句 error_msg 更有指导性。
--
-- 行粒度 = (文档, 页码)。同一页有多条问题时由 reason 承载并列描述 ——
-- 不再细分到"每个表格一行"，因为前端告警条只按页展示（`KbUploadView` 的 issue-bar）。
--
-- 无"全文级"哨兵值：page_no 一律是真实页码（1-based）。凡是与具体页无关的整体性
-- 失败（编码错误、格式不支持）走 sys_document.error_msg，**不进本表** ——
-- 那样才不会有"page_no = 0 是什么意思"这种要靠注释才能读懂的行。
-- ---------------------------------------------------------------------------
CREATE TABLE sys_parse_issue
(
    id         BIGINT       NOT NULL AUTO_INCREMENT,
    doc_id     BIGINT       NOT NULL COMMENT '归属文档（T-511 的 docId）',
    kb_id      BIGINT       NOT NULL COMMENT '所属知识库：本接口的主要过滤条件，冗余以避免每次 join sys_document',
    page_no    INT          NOT NULL COMMENT '页码，1-based，与 PDF 页序一致（T-511 点名的字段）',
    reason     VARCHAR(512) NOT NULL COMMENT '可执行的原因（02 §静默降级视为缺陷：不许只说"失败"两字）',
    created_at DATETIME     NOT NULL COMMENT '发现时间；重跑解析后整批重建，故它也是"最近一次解析"的时间',

    PRIMARY KEY (id),
    -- 重跑解析时按 doc_id 先删后插（幂等），故这个索引是写路径的必要条件
    KEY idx_issue_doc (doc_id),
    -- 列表查询按库过滤（GET /kb/{kbId}/parse-issues）
    KEY idx_issue_kb (kb_id)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci COMMENT ='逐页解析问题（驱动上传页顶部告警条）';
