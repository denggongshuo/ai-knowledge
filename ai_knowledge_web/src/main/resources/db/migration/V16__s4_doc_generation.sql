-- ---------------------------------------------------------------------------
-- S4 · 阶段 D：sys_document.index_generation（T-406 重建的**断点**）
--
-- G3-6 的判据是「中断后重启，**从断点继续（不重跑已完成文档）**」。要满足它，
-- 就必须能回答"这篇文档的向量**已经完备地**落在哪一代"。本列就是那个答案。
--
-- ---------------------------------------------------------------------------
-- 为什么不能靠"查 Milvus 里有没有这篇文档的点"来判断
-- ---------------------------------------------------------------------------
-- 向量写入是 DocStorage 式的「先删后插」（replaceDocument，C3 已证其幂等）。
-- 进程在 delete 之后、insert 完成之前被杀，这篇文档在新分区里是**半截**的：
--   · 一条都没有  → "查得到吗"判否 → 会重跑（正确）
--   · 写进去一部分 → "查得到吗"判**是** → 会被**误 skip**，留下一篇缺块的文档
--                   却标着可检索 —— 正是本项目最不能接受的静默故障形态。
-- 所以判据不能是"在不在"，必须是"**完没完**"，而"完"只能由写入方在**成功之后**记下来。
--
-- ---------------------------------------------------------------------------
-- 为什么落在 sys_document 而不是新开一张进度表
-- ---------------------------------------------------------------------------
-- 它是**这一行文档自己的事实**（"我的向量在第几代是齐的"），与 status / chunk_count
-- 同一性质。单开一张"重建进度表"会让同一个事实有两个地方要同步，而那里的行
-- 在重建结束后就是垃圾。
--
-- DEFAULT 0 = "没有向量"（不是"第 0 代"）。首代从 1 起（同 sys_kb.index_generation），
-- 所以 0 是一个**不会被任何真实代占用**的哨兵值 —— 8 个演示库的既有行语义天然正确。
--
-- ⚠️ 与 sys_kb.index_generation 的关系（两者不是一回事）：
--   · sys_kb.index_generation      = **检索该查哪一代**（切换点，D-7 的原子性所在）
--   · sys_document.index_generation = **这篇文档的向量写齐了哪一代**（断点依据）
--   重建期间两者会**故意不一致**：kb 还指旧代（检索照旧可用），而文档一篇篇
--   变成新代。全部完成后才切 kb 那一列。若文档的值 != kb 的值，说明这篇文档
--   在当前代里还没有齐备的向量 —— 检索侧据此可以把它排除（而不是召回一篇残的）。
--
-- 不加索引：唯一按它筛选的场景是重建时"跳过已完成的文档"，量级是**单个库的文档数**，
--   且已经在按 kb_id 过滤之后（sys_document 有 idx_doc_kb）。与 V10 同一条判断。
--
-- ⚠️ 跑过的迁移**只增不改**：V1~V15 一行不动，本次改动全部落在这里。
-- ---------------------------------------------------------------------------

ALTER TABLE sys_document
    ADD COLUMN index_generation INT NOT NULL DEFAULT 0
        COMMENT '该文档向量写齐的代数（0 = 无向量；首代从 1 起）。T-406 重建的断点依据 —— 不能用"查 Milvus 在不在"代替，半截写入会被误 skip';
