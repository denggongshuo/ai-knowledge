-- V18 · S4-E2（优化/O2 页级文本层与多模态路由）
--
-- 本批把「无文本层」判定从**文档级**下沉到**页级**，混合型文档（38 页文本 + 2 页扫描）
-- 不再静默丢页。要落两件事：
--   ① 文档级多两列 —— 「40 页里 38 页有文本」比「平均 300 字/页」信息量大得多；
--   ② issue 多两列 —— 种类与处置，从"拼在 reason 前面的文字前缀"提升为**可查询的列**。
--
-- ⚠️ 页级判据取**绝对零**（chars == 0），**没有密度阈值** ——
--    `O2` §6 原本建议页级阈值取 10，本批步 0 用 5 份真样本证伪了它：
--    10 会让 4 份正常文档里的 7 个页面误报（封面页 10 字 / PPT 导出页 11 字 / 截图页 8 字，
--    它们**都有文本层**，只是作者写得少）。真扫描页是 0 字，**间隙干净（0 vs 最小 8）**。
--    依据与采样边界完整写在 `ParsedDocument#pageStats` 的 javadoc 与
--    `plan/2026-09-17-S4-E2.md` §3.4。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1) sys_document：页级文本层覆盖（`优化/O2` §4 步 6）
--
-- 为什么是**独立的质量列**而不是由 status 派生：
--   与 V12 那四列（table_total/table_parsed/image_total/image_parsed）同一条理由 ——
--   《06》§3.6：解析质量是**静默故障**，两行的状态列一模一样，只有质量列才看得出差别。
--   一篇 3000 字 / 40 页的文档 charsPerPage=75 看着健康，而 pages_with_text=6
--   说明 34 页是扫描页 —— 只看 status 与 chars 永远发现不了。
--
-- ⚠️ **NOT NULL DEFAULT 0** 是一处刻意的取舍，前端必须配合：
--   - 旧行（本批之前落的）落 0/0，语义是「**尚未统计过**」；
--   - 真·统计结果为 0 页的文档（整篇扫描件）也是 0/0。
--   两者在列上**不可区分** —— 但可以：整篇扫描件的 status 必是 FAILED，
--   而"尚未统计"的只可能是 READY/INDEXING 的旧行。
--   所以**前端必须把 `pagesTotal == 0` 渲染成「—」而不是「0/0 页有文本」** ——
--   后者是在断言"这篇一页都没文本"，而事实是"这行还没被本批重跑过"。
--   这也正是本列不做成可空的原因：可空会让每处读取都多一个 null 分支，
--   而"0 与未统计"的歧义只有**一个消费点**（文档列表的质量列），在那里判一次就够。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_document
    ADD COLUMN pages_total      INT NOT NULL DEFAULT 0
        COMMENT '解析出的总页数（优化/O2；0 = 本批之前落的旧行，尚未统计）',
    ADD COLUMN pages_with_text  INT NOT NULL DEFAULT 0
        COMMENT '其中判定为「有文本层」的页数（优化/O2；口径 = 该页 chars > 0，无密度阈值）';

-- ---------------------------------------------------------------------------
-- 2) sys_parse_issue：种类与处置提升为列
--
-- 此前（S4-M05-C2 步 0.6）`kind` 是**拼在 reason 前面的文字前缀**（【无文本层】…），
-- 当时的理由是「本批不加迁移」。代价写在 IssueKind 的 javadoc 里：
--   「种类在库里是文字，不是可查询的列。要按种类过滤就得加列 ——
--     那件事留给真正需要它的批次。」
-- **本批就是那个批次**：`O2` 的判据 2 要求 `kind` 与 `disposition` **可查**
-- （前端要按 disposition 分流"要不要管"），文字前缀满足不了。
--
-- 为什么要**两**列而不是一列：
--   种类回答「这是什么问题」，处置回答「**这个问题被怎么办了**」—— 正交。
--   同一个"无文本层"可以是 MISSING（v1：没能力补）也可以是 OCR_FILLED（S6：已补全，
--   内容已能检索）。挤在一个字段里，接 OCR 的那天就没法区分
--   "这篇还会复发"与"这篇已解决"。枚举先行、能力后接。
--
-- ⚠️ 可空（NULL）而不是 NOT NULL DEFAULT：
--   旧行没有种类信息，回填出来的是**猜的**。NULL = 「未知」，前端按未知展示、**不伪造** ——
--   与 `sys_audit_log.affected_role` 历史 1262 行全 null 的处置同一条纪律。
--   新行由 `DocRecordWriter#replaceIssues` 保证两列都非空。
--
-- ⚠️ **reason 不再带前缀**（回归纯原因文本）：写入侧改用列之后，再拼前缀就是
--   同一信息存两份、且两份会漂。旧行的前缀留在 reason 里不动（那是历史事实）。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_parse_issue
    ADD COLUMN kind        VARCHAR(32) NULL
        COMMENT '问题种类（ParsedDocument.IssueKind 名；NULL = 本批之前的旧行，未回填）',
    ADD COLUMN disposition VARCHAR(16) NULL
        COMMENT '处置结果（MISSING 未处理 / OCR_FILLED 已补全 / EMPTY_PAGE 空白页，见 Disposition）';

-- 不加索引：两列当前只**随** doc_id/kb_id 过滤后返回，没有独立的筛选入口
--   （前端告警条按 docId 去重、按 disposition 分流展示，都在 100 行截断内）。
--   等真出现"只看已补全的"这类筛选需求再加 —— 那时也能看清真实的查询形状。
