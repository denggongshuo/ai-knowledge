-- ===========================================================================
-- S5 · 阶段 A：内容指纹、样板标记、向量模型归因（`T-O09` 步 1/2/3/4/7）
--
-- 三件事的共同点：它们都是**描述已有事实**的列，不改变任何既有行为。
--   · content_sha256      —— 这段文本"是什么"，用于内容级去重（O9 步 1）
--   · is_boilerplate      —— 这段文本"是不是跨文档样板"（O9 步 3/4）
--   · embed_model_id/ver  —— 这条向量"是谁产的"（O9 步 7）
--
-- 五列全部**可逆**（DROP COLUMN 即可，无需回填业务数据）。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- sys_document.content_sha256 —— 文档级内容指纹
--
-- 为什么不是 md5：`sys_document.md5` 已经是字节级指纹，而它**回答不了**
-- "这两个文档是不是同一份内容" —— DOCX 转存成 PDF、改一句话的合同 v2、
-- 换个工具另存一遍，字节全都不同而内容几乎一样（O9 §2.1 的三行表）。
-- 这一列才是那个问题的答案。
--
-- 为什么 CHAR(64) 而不是 BINARY(32)：sha256 的十六进制表示是**定长** 64 字符，
-- CHAR 在 utf8mb4 下存储长度固定、比较无需前缀扫描；而 BINARY 会让
-- "用 SQL 手工核对"变成一件要 hex() 包一层的事。指纹类字段的可读性是有价值的。
--
-- NULL 语义：本批之前入库的文档为 NULL。**两侧都非空才比较** —— 两个 NULL
-- 不是"相同的指纹"，那是"都没有指纹"（见 DocService 的判据）。
--
-- ⚠️ 已知风险（O9 §6 点名，必须写在这里）：指纹只在**同一解析器版本内**可比。
-- 升级 Tika/opendataloader 后同一份文件的抽取文本可能变化，于是指纹跟着变 ——
-- 表现为"升级后重复告警突然消失"。本批的口径是**只做同版本比较**（不把
-- parserVersion 并进指纹输入，那样会让比对永远不命中且更难解释）。
-- 真要跨版本比对，得等 O5 的版本指纹落地后一起做。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_document
    ADD COLUMN content_sha256 CHAR(64) NULL
        COMMENT '规范化文本的 sha256（64 位小写十六进制）。O9 内容级去重；NULL = 本批前的旧数据' AFTER md5,
    ADD KEY idx_doc_csha (content_sha256);

-- ---------------------------------------------------------------------------
-- sys_chunk.content_sha256 —— 分片级内容指纹
--
-- 两个用途：① 样板识别的计数键（O9 步 3 按它跨文档统计）；
-- ② 同一文档内"这段和那段一模一样"的判别依据。
--
-- 与 sys_document.content_sha256 是**同一套算法、不同粒度**：前者是整篇规范化文本，
-- 后者是单块规范化文本。两者不可互推 —— 一篇文档的指纹不等于它任何一块的指纹。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_chunk
    ADD COLUMN content_sha256 CHAR(64) NULL
        COMMENT '分片规范化文本的 sha256。O9 样板计数键；NULL = 本批前的旧数据' AFTER raw_content;

ALTER TABLE sys_chunk
    ADD KEY idx_chunk_csha (content_sha256);

-- ---------------------------------------------------------------------------
-- sys_chunk.is_boilerplate —— 跨文档样板标记（O9 步 4）
--
-- 为什么是**独立布尔列**而不是 chunk_type 的一个新取值：`chunk_type` 是
-- **8 个固定取值的块类型域**（D-5 §1.3），它是"这个块是什么形状"；
-- 而样板与否是"这段文本在语料里出现了多少次" —— 同一段免责声明可以是
-- PARAGRAPH，也可以是 LIST。塞进 chunk_type 会让"类型"这个维度失去意义。
--
-- DEFAULT 0 = 非样板。**不是"未判定"** —— 冷启动期（语料不足 20 篇）
-- 所有块都是 0，那正是"还不能判定为样板"的正确表达。
--
-- 保留而不删除（O9 §6 明确不做自动删除）：删了以后"为什么这段搜不到"
-- 就成了悬案，而这恰恰是用户最常问的问题。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_chunk
    ADD COLUMN is_boilerplate TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '1 = 跨文档样板（≥20 个文档含相同指纹且长度 200~2000），不进向量召回池。0 = 正常' AFTER content_sha256;

-- ---------------------------------------------------------------------------
-- sys_chunk.embed_model_id / embed_model_version —— 向量模型归因（O9 步 7）
--
-- 为什么记在 **sys_chunk** 而不是 Milvus 的标量列：
--   · Milvus 集合本批刚为 BM25 重建过一次（10 列，见 MilvusConstants 的列数口径），
--     再加两列就是**第二次重建**；
--   · 而这两列是"这条向量的元数据"，不是"检索时的过滤维度" —— 检索从不按模型筛，
--     它只在**换模型要找出旧向量**时被查一次。那是一次离线操作，走 MySQL 完全够用。
--
-- NULL 语义：本批之前写入的向量为 NULL。界面按「未记录」渲染，
-- **不要显示成空字符串或"未知模型"** —— 那是两回事（"没记"vs"记不下来"）。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_chunk
    ADD COLUMN embed_model_id VARCHAR(64) NULL
        COMMENT '产出该分片向量的模型标识，如 BAAI/bge-m3。NULL = 本批前的旧向量' AFTER is_boilerplate,
    ADD COLUMN embed_model_version VARCHAR(32) NULL
        COMMENT '产出该向量时的模型配置版本（ModelConfigSpec#version）。与 embed_model_id 合起来唯一标识"哪一版配置干的"' AFTER embed_model_id;
