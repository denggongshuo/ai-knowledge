-- ===========================================================================
-- S5 · 阶段 B：`sys_document.chars`（`T-O05` 步 6 的度量来源）
--
-- 为什么单独一列（`O5` §4 步 6 点名的指标里有「平均 chars/页」）：
-- 它是**派生指标的分母/分子**，而分子原先没有落点 —— `parse.json`（对象存储）里
-- 有 `ParsedDocument.chars`，但"算一个聚合值要遍历 MinIO 读几千个 JSON"不是聚合该有的样子
-- （`O5` §4 步 6 的原话：「`sys_parse_issue` 是行级明细，缺**聚合**。企业运维要的是分布，
-- 不是 2000 行明细」）。落一列，聚合就退化成一条 `sum/chars`。
--
-- 与 `pages_total` 的关系：`pages_total` 来自同一份产物，两者相除即「平均 chars/页」。
-- 不分页的格式（TXT/MD）`pages_total = 0`，读侧必须按"整篇一页"兜底
-- （与 `ParsedDocument#charsPerPage` 同一条口径，别在两处各判一次）。
--
-- `DEFAULT 0` 的语义：**尚未解析 / 解析产物没有可检索文本**。
-- 两者在聚合里都算 0 是对的 —— 这个指标问的就是"抽到了多少内容"。
-- 演示数据（`V6` 的常驻设施）不含文档，故无需回填。
--
-- 可逆：`DROP COLUMN` 即可。
-- ===========================================================================

ALTER TABLE sys_document
    ADD COLUMN chars INT NOT NULL DEFAULT 0 COMMENT '可检索文本量（ParsedDocument.chars 的回填）；0 = 尚未解析或没有可检索文本';
