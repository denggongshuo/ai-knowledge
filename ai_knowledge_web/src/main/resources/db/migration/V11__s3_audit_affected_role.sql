-- ---------------------------------------------------------------------------
-- S3 · 阶段 C：sys_audit_log 补「受影响角色名」（T-302 详情抽屉的 W1 修复）
--
-- 为什么需要这一列（这条是本批最难查的一类错：数字对、格式对、语义错）：
--   前端 AuditLogView.vue 的详情抽屉把 roleName 当**受影响角色**用 ——
--   :337 渲染「{affectedUsers} 人（{roleName}下全部成员）」，
--   :349 用它开「查看该角色当前权限」按钮。而既有的 role_name 列存的是
--   **操作人自己的角色码**（AuditAspect#build 从 LoginUser.getRoleCodes() 写，
--   列注释也写着「操作人角色」）。两者语义相反。
--   接真后端后的症状：抽屉显示「12 人（SUPER_ADMIN 下全部成员）」——
--   人数是数据库里真有的、格式也合法，只有括号里那个角色名是错的。
--
-- 为什么**不改 role_name 的语义**（加列而不是改写）：
--   role_name 的 1262 行历史值是「操作人角色」，那是**另一个事实**且已在库里。
--   改语义 = 要重写全部历史（把操作人角色码冲掉），**不可逆**；
--   而且"操作人角色"本身将来仍可能需要（谁在用超管身份操作）。
--   两列并存、各自有注释说明区别，比"一个列名两种含义"安全得多。
--
-- 为什么可空、且不回填：
--   只有权限变更类动作才有"受影响角色"（当前 3 个写入点：功能矩阵 / 知识库授权 /
--   编辑用户）。其余动作没有影响面，null 是准确的。历史 73 行有 affected_users
--   但没有角色名 —— 那是准确的历史（当时没记），**不伪造**：
--   详情接口在 affected_role 为 null 时返回 roleName=null，
--   前端 :337 的三元与 :349 的 v-if **已有守卫**，会自动省略括号与按钮，
--   不会渲染出「12 人（null 下全部成员）」。
--
-- 不加索引：本列不做筛选条件、只随详情返回（详情按主键查一行）。
--
-- ⚠️ 跑过的迁移**只增不改**：V1~V10 一行不动，本次改动全部落在这里。
-- ---------------------------------------------------------------------------

ALTER TABLE sys_audit_log
    ADD COLUMN affected_role VARCHAR(128) NULL
        COMMENT '受影响角色名（权限变更类动作才有）。与 role_name 语义不同：role_name 是操作人自己的角色码'
        AFTER affected_users;
