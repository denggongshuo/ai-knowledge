-- ===========================================================================
-- `T-O04` 余下：入库准入的恶意扫描与宏标记（`O4` 步 3 / 步 4）
--
-- 两道闸的落点，都是一列：
--   · `scan_status` —— 病毒扫描的结论（`CLEAN` / `INFECTED` / `SKIPPED`）；
--   · `has_macro`   —— 文档里有没有宏（`O4` §3 流程图 `K -- 含宏 --> L`）。
--
-- 为什么两列都**可空**，而不是给默认值
-- ---------------------------------------------------------------------------
-- `NULL` 与那两个枚举值表达的是**三件不同的事**，压成两件就会误导用户：
--
--   `scan_status`:
--     · `NULL`     —— **这条记录时还没有扫描这回事**（本迁移之前入库的历史行）。
--                     ⚠️ 它**不等于** `SKIPPED`：后者是"扫了、但没扫成"
--                     （ClamAV 未部署 / 连不上）。前者是"从没试过"。
--                     列表上两者的文案不同（历史行不该显示「未扫描」标记——
--                     那会让运维以为清理任务漏跑了）。
--     · `CLEAN`    —— 扫过，干净。
--     · `INFECTED` —— 扫过，命中。文档已被置 FAILED。
--     · `SKIPPED`  —— 没扫成（`O4` §6 的取舍：**默认走"未部署降级"**，
--                     不能因为本地没装 ClamAV 就把上传堵死）。
--
--   `has_macro`:
--     · `NULL` = 没检测过（历史行）；`0` = 检测过、无宏；`1` = 有宏。
--     `O4` §3 对宏的处置是「**放行 + 标记**」而不是拒收 —— 宏在内部知识库里
--     有正当用途（带宏的报表模板），一刀切拒收会误伤；而"下载/预览页提示"
--     需要这一列才显示得出来。
--
-- 为什么 `scan_status` 不做成 ENUM
-- ---------------------------------------------------------------------------
-- 本仓既有表里 `status` 一律用 VARCHAR（见 `sys_document.status` / `sys_async_task.status`），
-- 理由同 `MilvusConstants` 的分词器选择：**枚举可变而 DDL 不可变**——
-- 加一个取值就要一次 `ALTER TABLE`，而 `V*.sql` 跑过就不能改。
-- 取值域收在 Java 侧（`ScanStatus` 枚举），库层只存字符串。
-- ===========================================================================

ALTER TABLE sys_document
    ADD COLUMN scan_status VARCHAR(16) NULL
        COMMENT '恶意扫描结论：CLEAN/INFECTED/SKIPPED；NULL=该行早于扫描能力上线（≠SKIPPED）',
    ADD COLUMN has_macro TINYINT(1) NULL
        COMMENT '是否含宏：1 有 / 0 无 / NULL 未检测。含宏**放行 + 标记**，不拒收（O4 §3）',
    ADD COLUMN scan_note VARCHAR(255) NULL
        COMMENT '扫描结论的一句话说明；SKIPPED 时写"为什么没扫成"（未部署 / 连不上）';

-- `scan_note` 为什么值得一列而不是只进日志
-- ---------------------------------------------------------------------------
-- `SKIPPED` 的原因分好几种（开关关掉 / 服务不可达 / 返回了认不出的结论），
-- 而它们的处置**不一样**：前两种是"本地没装，生产上正常"，第三种是"扫描服务坏了、
-- 得去看它"。只把原因写进日志的话，页面上只有一个「未扫描」标记 ——
-- 运维分不出"这台机器本来就没装"和"生产上的扫描服务挂了"，
-- 而后者正是一次安全事件的开头。这一列就是给那个区分用的。

-- ⚠️ **不建索引**：这两列的筛选需求还没出现（列表上只是显示一个标记），
-- 而 `sys_document` 的行数在 v1 的量级（千级）下全表扫完全够。
-- 加一个没人用的索引是纯粹的写放大 —— 真要用时再按那时候的查询形态建。
