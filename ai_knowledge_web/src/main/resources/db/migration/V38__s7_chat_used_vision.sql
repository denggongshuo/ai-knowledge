-- =====================================================================
-- S7-M06-C · T-806 —— 「直接读原图」的**轮次痕迹**
-- =====================================================================
--
-- 需求 `09` §4.7 的「记录」那一行逐字写着：
--   「该轮消息标 `usedVision = true`，便于对比「用描述 vs 用原图」的回答差异」。
--
-- 为什么必须是**消息级**的一列，而不是会话级 / 也不是"从别处推得出来"：
--   · 会话级不行 —— §4.7 的另一句是「**只对该轮生效**」。同一会话里上一轮用描述、
--     下一轮点「直接读原图」，两者的回答质量要能分开看，这正是那一列存在的全部理由；
--   · 推不出来 —— 没有任何别的列记着"这一轮请求里 useVision 是什么"：
--     `sys_chat_attachment` 只到 `user_id`（承 `#162`：附件与消息的绑定本身还没做），
--     而请求体不落库。
--
-- ⚠️ 为什么可空而不是 `NOT NULL DEFAULT 0`：
--   本批之前的消息行**没有采集过**这件事。给它们填 0 就是一句关于内容的断言
--   （"这一轮没用原图"），而事实是"当时没记"。两者的区别与
--   `top1_score` / `rerank_before_top1` 那两列同一条口径
--   （"没测到"与"得了 0"是两件事，见 `V35` 的头注与 `汇总.md` §5）。
--   ⇒ **不回溯填 0**；前端在 `null` 时**不显示**「已读原图」。
--
-- 口径：
--   NULL = 未采集（本批之前的行）
--   0    = 这一轮明确**没有**走原图（含没带图、带图但走 VL 描述）
--   1    = 这一轮明确**走了**原图（`useVision=true` 且模型声明支持视觉）
-- =====================================================================

ALTER TABLE sys_chat_message
    ADD COLUMN used_vision TINYINT(1) NULL
        COMMENT '本轮是否把原图直接传给对话模型（T-806 · 需求 07 §6.12 / 09 §4.7）。NULL = 未采集（本批之前的行），0/1 = 明确的两态。只对该轮生效，不是会话级';
