-- ===========================================================================
-- V41 · S7 · M06 阶段 F —— 回收站的「删除人」（门禁 `G7-10`~`G7-14`）
--
-- **只加两列**，不改任何既有列、不动任何行。
-- 由来：需求 `06` §7.9 逐字写「软删除：加 `deleted_at` + **`deleted_by`**」，
--   §7.4 的列表字段表里也有「删除人」一列。
--   而施工前实测（`information_schema`）：全库有 **4 张**表带 `deleted_at`
--   （`sys_document` / `sys_kb` / `sys_user` / `sys_chat_session`），
--   **没有任何一张带 `deleted_by`** —— 这张表此前根本没人做过。
--
-- 🔴 **为什么加列而不是从 `sys_audit_log` join 出来**：
--   审计里确实记了「谁删的」（`删除文档` / `删除知识库` 两条动作都在），
--   但审计行的 `target` 是**自由文本**（形如 `文档#123`），与具体行**没有可 join 的键**
--   —— 靠正则从 target 里抠 id 去 join，是把"能查到"赌在文案不变上。
--   而且审计是**合规留痕**（append-only、永久保留），回收站是**用户界面**
--   —— 让一个界面的列表去扫审计表，两个消费者的寿命与语义都不一样。
--
-- ⚠️ **`deleted_by` 可空，且存量行为 NULL**：V41 之前被软删的行（演示库里当前没有，
--   但生产可能有）**在任何地方都查不到"是谁删的"** —— 审计里那条的 target 也只是文案。
--   这类行在回收站列表里如实显示「—」（不编一个"未知用户"）。
--
-- ⚠️ **不建外键**（与 `owner_id` / `kb_id` 同族）：用户被删之后，
--   「这个人当初删了这篇文档」这件事**仍然要留着** —— 建 FK 会让删用户失败
--   （或级联把回收站清空），两种都不是我们想要的。
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- sys_document.deleted_by —— 把这篇文档移入回收站的人
-- ---------------------------------------------------------------------------
-- ⚠️ 位置紧跟 `deleted_at`：两列是一对（"什么时候删的" + "谁删的"），
--   分开放会让下一个读表的人以为 `deleted_by` 是别的东西。
ALTER TABLE sys_document
    ADD COLUMN deleted_by BIGINT NULL
        COMMENT '删除人 id（T-611 软删时写入）。NULL = 该行在 V41 之前被删，删人已不可考'
        AFTER deleted_at;

-- ---------------------------------------------------------------------------
-- sys_kb.deleted_by —— 把这个知识库移入回收站的人
-- ---------------------------------------------------------------------------
-- ⚠️ 与文档侧**同一条口径**。⚠️ 注意本表的软删**不级联**（`KbLifecycleService#softDelete`
--    只写 kb 行）⇒ 恢复知识库时其文档**从未被动过**，`G7-11` 的「连带恢复」
--    在现实现下是**零动作**（只清 kb 的 `deleted_at`）。回收站列表的
--    `docCount`（影响多少篇）由 `sys_document` 现查。
ALTER TABLE sys_kb
    ADD COLUMN deleted_by BIGINT NULL
        COMMENT '删除人 id（T-407 软删时写入）。NULL = 该行在 V41 之前被删，删人已不可考'
        AFTER deleted_at;
