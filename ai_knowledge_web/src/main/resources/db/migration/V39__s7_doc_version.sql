-- ===========================================================================
-- V39 · S7 · M06 阶段 D —— 文档版本历史（不变量 `I-5`）
--
-- 给 `sys_document` 加**三列** + **一个索引** + **回填存量**。没有新表。
-- 版本模型的选型（为什么"每个版本一条 doc 行"而不是独立版本表）写在计划 §5，
-- 一句话：分片 / 向量 / 检索 trace **全部按 `doc_id`** 组织 ⇒ 每个版本自成一条
-- `sys_document` 行时，历史版本的分片天然独立保留，回滚只需复制分片再向量化。
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- ① 三列：doc_group_id / version_no / is_current
-- ---------------------------------------------------------------------------
-- 由来：需求 `06` §6.4（版本历史）+ 不变量 `I-5`：
--   「同名文件重新上传时，**直接覆盖会让历史问答的引用指向新内容，造成答案对不上**」
--   ⇒ 设计为「**同名上传默认归档为新版本，而不是覆盖**」，用 `(docGroupId, version)` 组织，
--   且「**只有当前版本参与检索**，历史版本不建索引」。
--
-- 🔴 **地基是当初就预留的**：`V12:73` 的 `idx_doc_md5` **刻意不是唯一索引**，注释逐字写
--   「覆盖 = 归档为新版本，v2 与 v1 共享同一 md5，硬唯一约束与它不能同时成立」⇒
--   本迁移是把那句注释兑现成列。
--
--   · doc_group_id —— 版本组。同名归档的多个版本共享同一组值。**回填成自身 id**
--     （见 ③）：存量每篇文档各自独立成组，是它自己那一组的唯一（当前）版本。
--     ⚠️ 可空只是为了"加列时先不写值、随即回填"；回填后**逻辑上恒非空**。
--   · version_no —— 组内版本号，从 1 起。同名归档时新行取 `max(version_no)+1`。
--   · is_current —— 是否当前版本。🔴 **它是 `G7-5` 的落点**：检索侧只放行 `is_current=1`
--     的文档（见 ②）。一个组内**恰有一行** `is_current=1`（归档 / 回滚时旧行翻 0、新行置 1）。
--
-- ⚠️ **什么触发"归档为新版本"**：需求 §3.2（命中 `(owner_id,md5)` 覆盖，内容**相同**）与
--   §6.4（同名文件**更新**，内容**变了**）在触发口径上打架 —— 用户 2026-09-21 裁定
--   **同名触发**（判定键 `(kb_id, owner_id, file_name)`），md5 只继续做"秒传/是否覆盖"的
--   **提示**，不再参与版本判定。这与本仓「去重是提示型不是约束型」的硬口径一致。
-- ---------------------------------------------------------------------------
ALTER TABLE sys_document
    ADD COLUMN doc_group_id BIGINT NULL
        COMMENT '版本组（I-5）：同名（kb_id+owner_id+file_name）归档的多个版本共享同一组值；回填 = 自身 id（各自独立成组）',
    ADD COLUMN version_no INT NOT NULL DEFAULT 1
        COMMENT '组内版本号，1 起；同名归档 / 回滚时新行取 max(version_no)+1',
    ADD COLUMN is_current TINYINT(1) NOT NULL DEFAULT 1
        COMMENT '是否当前版本：只有当前版本参与检索（G7-5）；一个组内恰有一行为 1';


-- ---------------------------------------------------------------------------
-- ② 检索侧怎么用这三列 —— 写在迁移里，因为它是"这些列为谁而加"的唯一说明
-- ---------------------------------------------------------------------------
-- `RetrievalScope#visibleDocIds` 已有 `deleted_at is null` + 密级白名单两个合取项，
-- 本批只再补**一个合取项**：
--
--       and d.is_current = 1
--
--   它把"历史版本"整体挡在召回之外 —— 这正是 `G7-5`「上传新版本后旧版本不再被召回」。
--   🔴 **它必须配一条证伪判据**（`RetrievalScopeFlowTest`）：去掉这个合取项 ⇒ 旧版本
--   的 doc_id 又进召回 ⇒ 用例当场转红。否则"加了一个 where 条件"这件事本身是没有证据的。
--
-- 🔴 **为什么不靠"历史版本没有向量"来实现，而要在 SQL 里挡**：归档时确实会**清掉旧版本的
--   Milvus 向量**（`DocService#upload` 里 `replaceDocument(oldPartition, oldDocId, [])`），
--   但那是**运行期动作**，可能因中断 / 竞态留下残迹；SQL 合取项是**确定性**的第二道，
--   两道都要（与本仓"检索侧过滤不能只靠一处"同一条纪律）。
--
-- ⚠️ 回滚（`G7-6`）**不动** `sys_retrieval_trace_chunk`：历史问答的引用锚定在那张表的
--   `chunk_id/doc_id`（`V22:140`），回滚只新增版本行、不删旧 doc/chunk 行 ⇒ 旧引用
--   天然仍指向旧内容。这就是需求 §6.4「回滚**历史问答的引用不会改变**」的实现。
-- ---------------------------------------------------------------------------


-- ---------------------------------------------------------------------------
-- ③ 回填存量：每篇文档各自成组、v1、current
-- ---------------------------------------------------------------------------
-- 存量文档在此之前**没有版本概念** —— 每篇就是它自己那一组的唯一版本。
-- 于是 doc_group_id = id（自身）、version_no = 1（DEFAULT 已给）、is_current = 1（DEFAULT）。
-- ⚠️ 只需回填 doc_group_id：另两列的 DEFAULT 在加列时已对存量行生效。
-- 🔴 **含软删行也要回填**：软删文档（deleted_at 非空）将来从回收站恢复时仍要有组身份，
--   不回填会让它恢复后 doc_group_id 为 NULL（一个没有组的"当前版本"，版本列表查不到它）。
-- ---------------------------------------------------------------------------
UPDATE sys_document SET doc_group_id = id WHERE doc_group_id IS NULL;


-- ---------------------------------------------------------------------------
-- ④ 索引：版本列表按组取 + 按版本号排序
-- ---------------------------------------------------------------------------
-- `GET /doc/{id}/versions` 先由 id 查出 doc_group_id，再 `where doc_group_id = ?
--   order by version_no desc` 取全组 ⇒ (doc_group_id, version_no) 复合索引直接覆盖。
-- 检索侧的 `is_current = 1` **不单独建索引**：与 `V37` 里密级列同一条理由 ——
--   `is_current` 是低基数（0/1），而同一 WHERE 里 `kb_id in (...)` + `deleted_at is null`
--   已把行集缩得很小，给低基数列建索引优化器不会选它，只多一份写开销。
-- ---------------------------------------------------------------------------
CREATE INDEX idx_doc_group ON sys_document (doc_group_id, version_no);
