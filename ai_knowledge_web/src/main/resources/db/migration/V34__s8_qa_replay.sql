-- ===========================================================================
-- V34 · S8-M10-B（`T-A01`）· 重放验证：补录备注
--
-- 需求 `08-需求-运营分析.md` §1.4 闭环第 2 步：「**一键补文档** —— 带问题跳上传页，
-- **问题文本作为补录备注带入**」；第 4 步「**自动重放验证** …… 重放要同时校验两件事：
-- ① 召回分是否提升；② 新召回的**确实是不是刚补录的那篇文档**」。
--
-- ---------------------------------------------------------------------------
-- 为什么必须新增这一列 —— 需求说了"带入"，但全仓没有"补录备注"这个落点
-- ---------------------------------------------------------------------------
-- 施工前实测（本批 §1 第 3 条）：`sys_document` 没有 remark 列、`DocController#upload`
-- 只收 `file`、`docs/需求文档/06` 里"备注"零命中。于是闭环在**第 2 步与第 4 步之间断了**：
-- 上传页拿不到问题文本，重放也认不出"哪一篇是刚补录的"。
-- 用户 2026-09-20 裁定照需求写的机制补上（`AskUserQuestion` 选「照需求写：加 remark 列」）。
--
-- ---------------------------------------------------------------------------
-- 🔴 这一列同时是"给人看的备注"和"重放验证的关联键"
-- ---------------------------------------------------------------------------
-- 重放要判断「新召回的确实是刚补录那篇」，就得知道"哪几篇是为这条未命中补录的"。
-- 关联方式**照需求写的**：把**问题文本**存进 `remark`，重放时用
-- `MissKeyNormalizer`（与未命中池**同一个归一化单点**）比对：
--
--     keyOf(document.remark) == keyOf(miss.question)
--
-- 于是备注与未命中**一一对应**（`sys_qa_miss.miss_key` 是唯一索引），
-- 且**不需要任何相似度阈值** —— 本仓在「没有语料就定阈值」上反复吃过亏（`T-O03` 至今卡着）。
--
-- ⚠️ **代价要写明**：人工改写备注会让关联断掉。这是**有意**的取舍 —— 需求把备注
-- 定义成人工字段（"带入"是给它一个初始值，不是锁死它）。断链的现象是
-- `hitSupplementedDoc = false`（如实回"这次没命中补录文档"），**不是静默错配**。
--
-- ⚠️ **为什么不给 sys_qa_miss 加一列 `supplemented_doc_id`**：那样关联会硬得多，
-- 但需求描述的机制是"带问题文本"，不是"带 miss id"，而上传页在
-- 「清单行跨多个知识库」时会退化成"跳知识库列表让用户自己选库"
-- （`OpsQaView.supplement()` 的既有分支），那时它**手里只有问题文本、没有 miss id**。
-- 照需求写的那条路在这种情形下**照样成立**。
--
-- ---------------------------------------------------------------------------
-- 为什么没有索引
-- ---------------------------------------------------------------------------
-- 找补录文档的扫描面是「`remark` 非空且未删的文档」—— 只有**补录产出**的那几行
-- （正常上传不写备注）。为一个几十行的集合加索引，是在为写入付代价而没有读的收益。
-- 真长到需要索引那天，加一个前缀索引即可（`KEY idx_doc_remark (remark(64))`）。
--
-- ---------------------------------------------------------------------------
-- 可逆
-- ---------------------------------------------------------------------------
-- `ALTER TABLE sys_document DROP COLUMN remark`。回滚会让已完成的重放关联失效，
-- 但那属于"重放结论"而不是业务数据，不构成不可逆损失。
-- 迁移文件编号依现有最大编号递增：V33 → **V34**。
-- ===========================================================================

ALTER TABLE sys_document
    ADD COLUMN remark VARCHAR(500) NULL
        COMMENT '补录备注（需求 08 §1.4 步 2）：从运营页跳上传页时把未命中问题文本带入。⚠️ 它同时是重放验证的**关联键**（归一化后与 sys_qa_miss.question 比对，见 MissKeyNormalizer）；人工改写它会断链，这是有意的';
