package com.knowledge.ai.pipeline.enhance;

import java.util.List;

/**
 * `T-507` 的提示词 —— **集中一处**（计划 §3.1 的 2.3：可测、可换）。
 *
 * <h3>为什么提示词要单独一个类</h3>
 * <p>三个理由，都不是审美：
 * <ol>
 *   <li><b>可断言</b>：测试要能断言"提示词里确实带了这段正文 / 确实要求了 JSON 格式"。
 *       拼在业务方法里就只能断言"调用次数"，而那证明不了模型看到了什么；</li>
 *   <li><b>可换</b>：模型或供应商一换，提示词往往要跟着调 —— 换的时候应该只动一处；</li>
 *   <li><b>可版本化</b>：{@link #VERSION} 让"这批摘要由哪版提示词产出"可追溯。
 *       摘要的质量无法自动评分（计划 §3.4 假设 3），版本号是事后对比的唯一锚点。</li>
 * </ol>
 *
 * <h3>输出格式为什么要求 JSON</h3>
 * <p>一次调用要产出**三样东西**（摘要 + 内容标签 + 实体关系，`I-10` 要求它们共享同一上下文
 * —— 分三次调用是三重成本与三重失败点）。一次调用产出三样就必须有个结构，
 * 而纯文本里塞三个字段只能靠约定分隔符，那比 JSON 脆得多。
 */
public final class EnhancePrompts {

    private EnhancePrompts() {
    }

    /**
     * 提示词版本 —— 换了措辞/格式要求就改它。
     *
     * <p>不是为了自动化，是为了**事后能回答"这份摘要是哪版提示词产出的"**。
     * 摘要质量要人工抽查（无法自动评分），抽查发现问题时要能定位到是哪一版。
     *
     * <p>⚠️ <b>2026-09-22（`S9-M12-A`）由 `doc-enhance-v2` → `v3`</b>：`relations` 的 JSON 结构
     * 多了一个 **`confidence`** 字段（`FR-GRAPH-01` 要求"关系必须带 confidence"，
     * 见 `docs/需求文档/07-需求-检索与问答.md:467`）。同时 `CacheConstants.PROMPT_VERSION`
     * 也要跟着 +1 —— 两处是**两个不同的东西**（这个是"产出物由哪版提示词产"的标签，
     * 那个是"旧缓存语义失效"的开关），本仓已经踩过一次"改了提示词而缓存继续命中"的坑。
     *
     * <p>⚠️ <b>2026-09-23（`S9-M12-C`）由 `v3` → `v4`</b>：要求 3 加了一条**实体名逐字照抄**
     * （不许同义改写 / 缩写 / 补全称）。它是 O 轨「锚定率」那条的动作项 ——
     * {@code RelationAnchor} 锚的是"实体名在块文本里的首次出现"，
     * 被改写过的实体名**在正文里不存在** ⇒ 关系被丢弃 ⇒ 图上没有边。
     * <p>🔴 **这次改动的效果**在 2026-09-23 的 relay 下**量不出来**：
     * {@code RelationAnchorRateProbeTest} 用的是**替身模型**（给死的 8 条关系），
     * 它读不到提示词 ⇒ 提示词怎么改都不影响它的数。所以本版**没有**前后两个锚定率，
     * 只有"改动的理由"。真实比例要在真模型可用时用同一个入口量（计划 §9 已登记）。
     */
    public static final String VERSION = "doc-enhance-v4";

    /**
     * 文档级提示词（1 次 / 篇）。
     *
     * <p>三条硬要求都写在提示词里，且各自对应一个真实的失败形态：
     * <ul>
     *   <li><b>只输出 JSON</b> —— 不然模型爱在前后写"好的，我来分析一下："
     *       （解析层有兜底，但那是在擦屁股，不是理由）；</li>
     *   <li><b>不许引入外部知识</b> —— 摘要是给检索用的，掺进模型自己的知识
     *       会让"文档里到底写了什么"变得不可信；</li>
     *   <li><b>抽不到就给空数组</b> —— 明写"不要编造"是因为**默认行为就是编造**，
     *       实体关系尤其明显。</li>
     * </ul>
     *
     * @param content 文档内容（调用方负责按预算截断）
     * @param truncated 内容是否被截断 —— **必须告诉模型**，否则它会把"只看到一半"
     *                  的摘要写得像"看完了全文"
     */
    public static String documentLevel(String content, boolean truncated) {
        return """
                你是企业知识库的文档分析助手。请阅读下面的文档内容，**一次性**产出四件事。

                严格按下面的 JSON 结构输出，不要输出任何其它文字、不要用 ``` 代码块围栏：
                {
                  "summary": "150~300 字的中文摘要",
                  "labels": ["3~8 个内容标签"],
                  "relations": [{"subject": "主体", "predicate": "关系", "object": "客体", "confidence": 0.9}],
                  "chapters": [{"title": "章节标题", "summary": "80~150 字"}]
                }

                要求：
                1. 摘要必须**完全基于**上面给出的内容，覆盖文档主题、适用范围与关键结论；
                   **不要引入文档之外的任何知识**，也不要写"本文介绍了……"这种空话套话。
                2. labels 用简短的名词（如「项目管理」「风险控制」），不要整句。
                3. relations 抽不到就给空数组 []，**不要编造**。
                   🔴 `subject` 与 `object` 必须是**内容里逐字出现过的原词**：
                   **原样照抄**，不要换同义词、不要写缩写、不要补全称、不要改单复数或大小写。
                   例：内容里写「路由表」就写「路由表」，**不要**写成「路由表服务」「routing table」。
                   原因：关系会被回源到正文——**照抄**才找得到出处；改写过就丢，那条关系等于白抽。
                   `confidence` 是你对**这条关系本身**的把握程度，取 0~1 的小数：
                   文中**明写**（如"X 基于 Y"）给 0.9 以上；**从上下文推出来**的给 0.5~0.7；
                   只是**猜测**给 0.3 以下 —— 它会被用来决定这条关系能不能参与检索跳转，
                   **猜的关系填高分会把不相关的内容带进答案**。
                4. chapters 是**逐章**摘要：`title` 必须与上面内容里的标题**逐字一致**
                   （不要改写、不要加序号、不要翻译），只对**在内容里真实出现过**的章节产出。
                   对每一章写 80~150 字，说清"这一章讲了什么"——它比文档级摘要更有用，
                   因为用户很少问"这篇讲了什么"，常问"第 3 章讲了什么"。
                   ⚠️ 若内容里没有可辨认的章节标题，就给空数组 []。
                5. 只输出 JSON 本身，第一个字符必须是 { ，最后一个字符必须是 }。
                %s
                ======== 文档内容开始 ========
                %s
                ======== 文档内容结束 ========
                """.formatted(truncatedNote(truncated), content);
    }

    /**
     * 分片级提示词（n 次 / 篇，`D-5` §1.6）—— 为**一个块**生成假设问句（HyQ）。
     *
     * <h3>为什么要生成"假设问句"</h3>
     * <p>用户的问法与文档的写法往往差得很远：文档写"令牌有效期 2 小时"，
     * 用户问"登录后多久要重新认证"。把**可能被问到的问句**也放进索引，
     * 就是在扩大召回面 —— 这是 HyQ 的全部价值。
     *
     * <h3>为什么一次只给一个块</h3>
     * <p>`D-5` §1.6 把它定成"分片级、逐分片独立调用"。这既是成本模型
     * （`O9` 的 63% 就出在这里），也是质量模型：一个块单独一次调用，
     * 模型能专注在"这段文字可能被怎么问"上，不会被别的章节带偏。
     *
     * @param blockText 块的原文（调用方负责长度预算）
     * @param max       最多生成几条 —— 多了会稀释向量（一个块塞 10 条问句，
     *                  嵌入结果变成 10 条问句的平均值，反而谁的都不像）
     */
    public static String hypotheticalQuestions(String blockText, int max) {
        return """
                你是企业知识库的检索优化助手。下面是一段文档内容，请推测**用户可能怎样提问**
                才会需要这段内容，并生成 %d 条中文问题。

                严格按下面的 JSON 结构输出，不要输出任何其它文字、不要用 ``` 代码块围栏：
                {
                  "questions": ["问题一", "问题二"]
                }

                要求：
                1. 问题必须**是用户会问出口的话**，不是对这段内容的概括。
                   反例（❌）：「介绍令牌有效期的配置」—— 这是标题，不是问句。
                   正例（✅）：「登录后多久需要重新认证？」
                2. 问题要**能由这段内容回答**。这段内容答不了的就不要问。
                3. 尽量覆盖不同的问法（事实型 / 操作型 / 原因型），不要三条都在问同一件事。
                4. **不要编造**内容里没有的信息（型号、数字、结论都不许加减）。
                5. 给不出问题就给空数组 [] —— 这比硬凑几条更有用。
                6. 只输出 JSON 本身，第一个字符必须是 { ，最后一个字符必须是 }。
                ======== 内容开始 ========
                %s
                ======== 内容结束 ========
                """.formatted(max, blockText);
    }

    /** 每条 HyQ 最多生成几个问句（`O9` 未给数，本批取 3 —— 见计划 §3.4 假设 3）。 */
    public static final int MAX_HYQ_QUESTIONS = 3;

    /**
     * 截断时的说明。
     *
     * <p>⚠️ 这一条不是客套：不告诉模型"内容被截断了"，它会**照常**写出一份
     * 听起来很完整的摘要 —— 而那份摘要缺了后半篇的内容，且**没有任何痕迹**。
     * 这正是本项目最忌讳的"少了一点东西而没人发现"。
     */
    private static String truncatedNote(boolean truncated) {
        return truncated
                ? "5. ⚠️ 注意：上面的内容**因长度限制被截断过，不是全文**。"
                + "请在摘要里如实反映这一点（例如以「（基于文档前半部分）」开头）。\n"
                : "";
    }

    /** 内容标签的兜底上限（模型偶尔会一口气给二三十个标签，全留着等于没有标签）。 */
    public static final int MAX_LABELS = 12;

    /** 实体关系保留上限 —— 与标签同理，且 `T-C00` 写图库时也需要一个上限。 */
    public static final int MAX_RELATIONS = 30;

    /**
     * 章节摘要保留上限。
     *
     * <p>取 30：一次调用里多要 30 段 150 字的摘要，加上文档级那三样，
     * 输出量已在模型的舒适区内。再多会开始出现"写到一半就断"（finish_reason=length），
     * 而断掉的那次会让**整个**文档级增强判 BAD_OUTPUT —— 代价远大于多几章摘要的收益。
     */
    public static final int MAX_CHAPTERS = 30;

    /** 摘要长度上限（字符）—— 块是要被向量化的，超长摘要会变成一个畸形的检索条目。 */
    public static final int MAX_SUMMARY_CHARS = 2000;

    /** 供日志/测试展示本版提示词的组成（不含正文）。 */
    public static List<String> describe() {
        return List.of(VERSION, "文档级：summary + labels + relations（共享同一上下文，I-10）");
    }
}
