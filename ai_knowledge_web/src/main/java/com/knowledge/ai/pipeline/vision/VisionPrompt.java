package com.knowledge.ai.pipeline.vision;

/**
 * VL 描述的提示词模板（需求 `09` FR-SYS-04 §4.3）—— **逐字照抄，不"优化"措辞**。
 *
 * <h3>为什么要一个类，而不是把模板字符串放在调用处</h3>
 * <p>三条硬约束都挂在这个字符串上，分开写就必然漂移：
 * <ol>
 *   <li><b>{@link #PROMPT_VERSION} 是缓存 key 的第三段</b>（§4.8）。模板与版本号
 *       必须**改在一起** —— 只改模板不改版本号，缓存里的旧描述会一直生效，
 *       表现是「优化了 prompt 但毫无效果，且很难发现」（§4.8 的原话）；</li>
 *   <li><b>「最后一行输出关键词」是解析契约</b>。§4.4 明确说**不要**要求 VL 输出 JSON
 *       —— 很多 VL 模型会输出带 markdown 代码块或前后解释文字的 JSON，解析失败会
 *       **直接打断整条链路**。所以「最后一行的格式」与 {@code VisionDescriber} 的切分
 *       逻辑是一对，动其中一处必须动另一处；</li>
 *   <li><b>两条链路带不带用户问题</b>（§4.3 的对照表）：
 *       文档解析期**不带**（描述要能服务任何未来提问，必须中立完整）；
 *       问答期**带上**（VL 聚焦到与问题相关的区域，代价是描述不可跨问题复用
 *       —— 但提问传图本就一次性，不亏）。</li>
 * </ol>
 *
 * <h3>为什么 {@link #PROMPT_VERSION} 是手写常量而不是哈希</h3>
 * <p>用 {@code sha256(TEMPLATE)} 当版本号看着更"不会忘"，但它有一个坏处：
 * **改一个错别字也会让全库描述缓存失效**，而那种失效是静默的、要花真金白银重算的。
 * 手写常量把"这次改动值得让缓存失效吗"变成一个**要人回答的问题**，而
 * 忘了改的表现是"改了没效果"—— 那条已经被 §4.8 点名为最难发现的一类。
 * 取舍：宁可有人忘记改版本号（可查：模板变了而版本没变），也不要缓存被无意义地冲掉。
 */
public final class VisionPrompt {

    /**
     * 当前 prompt 版本。**改模板必须同时改它**（理由见类注释）。
     *
     * <p>取值形如 {@code v1} / {@code v2}；它是缓存 key 的第三段
     * （{@code md5(图片) : vlModelId : PROMPT_VERSION}）。
     */
    public static final String PROMPT_VERSION = "v1";

    /**
     * 描述模板本体（§4.3 的模板逐字）。
     *
     * <p>⚠️ 末尾那条「最后一行输出：关键词：…」是**结构性约定**，不是建议 ——
     * {@code VisionDescriber} 就是按它切两产出的。删掉它，切分逻辑会退化成
     * 「整段当描述，检索摘要 = 整段」，那样不报错、只是检索质量悄悄变差。
     */
    private static final String TEMPLATE = """
            【通用】你是文档图片理解助手。请对这张图片输出结构化描述，用于知识库检索。
            【先判类型】表格 / 图表 / 界面截图 / 流程图或架构图 / 照片实物
            【再按类型输出】
            · 表格 → 完整 markdown 表格（全部行列、数值、单位、表头）
            · 图表 → 图表类型 + 标题 + 坐标轴含义 + 关键数据点 + 趋势结论
            · 界面截图 → 页面名称 + 元素清单 + 全部可见文案与报错原文
            · 流程图 / 架构图 → 节点清单 + 连接关系（A → B）+ 图注
            · 照片实物 → 主体 + 关键特征 + 可识别文字
            【硬约束】
            1 数值、编号、版本号、错误码、金额、日期必须逐字保留，禁止概括为"若干 / 一些"
            2 无法辨认处写「[无法辨认]」，不要猜测
            3 只描述图中实际存在的内容，不补充常识推测
            4 输出纯 Markdown，不要包在代码块里
            5 最后一行输出：关键词：<8~15 个检索关键词，逗号分隔>""";

    /** 问答期带问题时追加的那一段（§4.3：「VL 会聚焦到与问题相关的区域」）。 */
    private static final String QUESTION_SECTION = """

            【用户的问题（描述请重点覆盖与该问题相关的区域，但图中其余内容也不省略）】
            """;

    private VisionPrompt() {
    }

    /**
     * 拼出送给 VL 的文本部分。
     *
     * @param question 用户问题。**文档解析期传 {@code null} 或空串** —— 那时描述必须中立完整，
     *                 带一个问题会让描述偏向那一问，而它要服务的是**未来所有**提问（§4.3）
     */
    public static String of(String question) {
        if (question == null || question.isBlank()) {
            return TEMPLATE;
        }
        return TEMPLATE + QUESTION_SECTION + question.strip();
    }
}
