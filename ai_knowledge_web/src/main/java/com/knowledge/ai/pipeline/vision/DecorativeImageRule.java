package com.knowledge.ai.pipeline.vision;

/**
 * 装饰图（跨文档重复的 logo / 图标）的判定规则（`T-O03`）—— **纯函数，无 IO、无状态**。
 *
 * <h3>三条条件，缺一不可</h3>
 * <ol>
 *   <li><b>跨文档</b>：同一张图（汉明距离 ≤ {@link #MAX_HAMMING}）出现在 ≥ {@link #MIN_DOCS} 篇
 *       文档里 —— 这条由调用方数好再传进来（它要读库）；</li>
 *   <li><b>不是「≈整页」</b>：面积 ≥ {@link #MAX_AREA} 的盒子**一律不判** —— 见下；</li>
 *   <li>（"尺寸/位置固定"这一条**不在本类**：`S6-M05-E` 把原计划的"分两层"收窄成
 *       **只做跨文档那一层**，理由见下。）</li>
 * </ol>
 *
 * <h3>🔴 为什么不做"单文档层"的判定（`S6-M05-D` §9-212 的改判）</h3>
 * <p>`O3` §4 步 3 原本是三条件，其中"尺寸/位置固定"是**文档内**就能判的。
 * 但 `C2` 的补探实测：在 {@code 健康生活方式}（**全扫描件**）上，
 * 「同一包围盒出现在 15 页」**恒成立**，而那个盒子就是**整页**
 * ⇒ 单文档层会把**扫描件的整页内容**判成装饰图。
 * <p>⇒ 而**跨文档**这条规则**天然不会**犯这个错：一份文档**永远到不了** {@link #MIN_DOCS} 篇。
 * 所以本批把它收窄成"只做跨文档那一层"—— 既避开那个假阳性，又保住 `O3` 自己点名的
 * **最强的那条判据**（原话是 pHash 跨文档重复）。
 *
 * <h3>🔴 「≈整页」的上界为什么是**绝对面积**而不是"占页面比例"</h3>
 * <p>因为**页面尺寸拿不到**：`S6-M05-E` 步 0 探针实测，5 份样本的 opendataloader JSON
 * 根字段一字不差全是 {@code [file name, number of pages, author, title, creation date,
 * modification date, kids]} —— **没有任何页宽/页高**。要补的不是我们的产物，是**上游库的产出**。
 * <p>⇒ 改用绝对面积。而探针量出**这条交界是清晰的**（5 份样本）：
 * <pre>
 *   内容图 / logo 那批：最大 180,829 pt²
 *   「≈整页」那批：     最小 499,877 pt²（595×841 ≈ A4）
 *                      另有 518,400 pt²（960×540，16:9 整页）
 * </pre>
 *
 * <h3>⚠️ {@link #MAX_AREA} 取的是**偏低**那一侧，理由不是"好看"</h3>
 * <p>两个方向错的代价**不对称**：
 * <ul>
 *   <li>取**低了**（把某些大图也排除）⇒ 它们**没被标成装饰图**，照常进召回池 ——
 *       是**漏报**，代价是多占几个召回名额；</li>
 *   <li>取**高了**（放过了整页图）⇒ **整页扫描内容被排除出召回池** ——
 *       是**误报**，代价是那部分内容**搜不到了**。</li>
 * </ul>
 * 本仓的排序是「**误报比漏报更伤**」（见 `DocumentCleaner`、`TextLayerGuard` 的同一条口径），
 * 所以 250,000 落在探针那条空档的**下半段**（180,829 ~ 499,877），离危险的那侧远一些。
 * ⚠️ **采样边界**：只有 **5 份样本、2 个"整页"实例**，且来自同一份扫描件为主。
 * 这是一个**按现有证据取的保守值**，不是标定值。
 *
 * <h3>⚠️ 另一条已知限制：dHash 只看水平差</h3>
 * <p>见 {@link ImageHash} 的类注释 —— 两张不同的图可能撞在同一个哈希上。
 * 判定因此压着"跨文档 + 面积上界"两条，**不能只靠哈希**。
 */
public final class DecorativeImageRule {

    private DecorativeImageRule() {
    }

    /**
     * 判定为装饰图所需的**最少文档数**（含本文档在内）。
     *
     * <h3>⚠️ 这个数**没有量过**，是本批最保守的一个默认值</h3>
     * <p>`O9` 的样板规则取 20（那是**文本**的语料统计）。图片不一样：一枚 logo
     * 通常只出现在**同一套文档**里（同一份手册的多个章节 / 同一系列的几个文件），
     * 跨 20 篇是罕见的。所以照抄 20 会让这条规则**几乎永不生效**。
     *
     * <p>取 **3** 的依据是"证据强度"而不是数据：**两篇**里的图相同**可能是巧合**
     * （比如两张都是纯色占位图），**三篇**就很难是巧合了。而方向上：
     * 取小了是**漏报**（少标几个装饰图），取大了才是**误报** —— 与 §类注释同一条排序。
     *
     * <p>⚠️ **拿到真实语料后必须重定**：本批没有多篇含同一 logo 的语料
     * （`C2` §8.5 已记：三份真样本**没有一份**含跨页同位置的图）。
     * 这一条登记在计划 §9。
     */
    public static final int MIN_DOCS = 3;

    /**
     * 判为"同一张图"允许的**汉明距离**上界（dHash 64 位里允许不同的位数）。
     *
     * <p>取 10：dHash 在"同源但被重编码"的图上通常差 0~6 位，而**不同**的图
     * 一般差 20 位以上。10 落在中间偏低处 —— 同样是"宁可漏报"那一侧。
     * ⚠️ 与 {@link #MIN_DOCS} 一样，**没有在本仓语料上量过**（没有正样本），登记在计划 §9。
     */
    public static final int MAX_HAMMING = 10;

    /**
     * 「≈整页」的面积上界（PDF 用户空间 pt²）。**≥ 它的盒子一律不判装饰图。**
     *
     * <p>取值与理由见类注释 —— 探针实测的空档是 180,829 ~ 499,877，本值落在下半段。
     */
    public static final double MAX_AREA = 250_000d;

    /**
     * 这张图**够不够格**参与装饰图判定（面积没到「≈整页」那一档）。
     *
     * <p>单独暴露它是为了让"为什么没被标"可回答 —— 与 {@code BoilerplateRule#lengthInRange}
     * 同一条理由：调用方要能区分"跨文档次数不够"与"它太大了"。
     *
     * @param area 包围盒面积（pt²）；{@code null} / ≤ 0 = 没有几何信息
     *             ⇒ **放行**（宁可漏报：没有几何不等于它就是整页）
     */
    public static boolean areaInRange(Double area) {
        return area == null || area <= 0 || area < MAX_AREA;
    }

    /**
     * 是否应标为装饰图。
     *
     * @param docCountWithSameImage **含当前文档在内**的、同库中含"这张图"的不同文档数
     * @param area                  该图片块的包围盒面积（pt²），可为 {@code null}
     * @return {@code true} = 标为装饰图，**不进向量召回池**
     */
    public static boolean shouldMark(long docCountWithSameImage, Double area) {
        return docCountWithSameImage >= MIN_DOCS && areaInRange(area);
    }
}
