package com.knowledge.ai.core.storage;

/**
 * **预签名 URL 的 TTL 口径**（`T-O06` 步 4 的「口径集中」半边 · `S5-M08-C`）。
 *
 * <h3>为什么要有这个类</h3>
 * <p>`T-O06` 步 4 原文是「预签名 URL 收窄：TTL 从**当前值**降到 5 分钟」。
 * 本批开工条件检查发现：**它点名的那个对象不存在** —— 全仓只有两处预签名
 * （头像、审计导出），而**文档下载/预览的预签名后端根本没有**（`DocController`
 * 只有 5 个端点，无 download/preview）。那条判据（"取一个 URL 等 6 分钟再访问应失效"）
 * 因此**挂起待 `T-614`**，与 `O6` 文档自己写的挂起一致。
 *
 * <p>能做的半边是**把散落的取值收成一处、并把"为什么是那个值"写下来** ——
 * 收窄本身只有在"这处 URL 确实会穿透某个 ACL"时才成立，
 * 而那个判断必须先看得见三个值各自站在什么理由上。
 * 拆分在不同类里的两个 `static final int` 做不到这件事：改的人只看到自己那一处。
 *
 * <h3>⚠️ 本类不回答「该不该收窄」，只回答「现在是多少、为什么」</h3>
 * <p>三个取值是**三个不同的取舍**，不是一个可以统一调的参数 —— 合并成一个
 * {@code PRESIGN_TTL} 是把三种风险压成一个数字，那正是本仓反复警惕的"静默拉平"。
 */
public final class PresignTtl {

    private PresignTtl() {
    }

    /**
     * 头像：**7 天**（单位天）。
     *
     * <p>不适用 `O6` 步 4 的收窄理由：那条理由是"URL 泄露就绕过密级/知识库权限"，
     * 而头像是**用户自己的展示图**，没有密级、没有 ACL 层次 —— 它泄露的最坏后果
     * 是"别人看到了你的头像"，而头像本来就是给所有人看的。
     *
     * <p>取值偏长的实际原因：前端把 URL 渲染进长期存在的布局（侧栏、评论），
     * 短 TTL 会让"页面挂了一小时后再重渲染"直接变成裂图。
     */
    public static final int AVATAR_DAYS = 7;

    /**
     * 审计导出件：**24 小时**（单位小时）。
     *
     * <p>它是 🚩 数据导出（高危），按 `O6` 的理由其实**够格收窄**。没收窄的原因是
     * **交付链路**：导出走异步任务（`AuditExportService#submit`），完成后经通知中心
     * 告知用户 —— 用户很可能是**第二天上班**才点开那条通知的。收到 1 小时会把
     * 这条链路变成"早上点开永远 403"。
     *
     * <p>⚠️ 这是一个**产品取舍，不是安全结论**：若哪天要求收窄，要同时改的是
     * 通知中心的话术与"重新签发"入口，而不是只把这里的数字改小。
     */
    public static final int AUDIT_EXPORT_HOURS = 24;

    /**
     * 运营报表导出件：**24 小时**（单位小时）。`T-A02` 新增。
     *
     * <p>与 {@link #AUDIT_EXPORT_HOURS} **同一条理由**（同一条交付链路：异步任务完成 →
     * 通知中心 → 用户可能第二天才点开），所以取同一个值。⚠️ 但两者的**敏感面不同**：
     * 审计件是"谁在何时做了什么"，运营报表含**提问原文 + 提问人姓名**
     * （`sys_qa_miss.question` / `last_user_id`）—— 后者的隐私成分更重。
     * <p>⇒ 收窄它比收窄审计件更有理由（`O6` 步 4 的原意），但**同样会打断交付链路**。
     * 真要收窄，一起动的是通知中心的话术与"重新签发"入口，不是只改这个数
     * —— 与审计件那边写的是同一条纪律。
     */
    public static final int OPS_EXPORT_HOURS = 24;

    /**
     * 问答图片附件：**10 分钟**（单位秒）。
     *
     * <p>它是本批**新出生**的surface，所以不存在"从当前值降下来"这件事 ——
     * 出生就按短 TTL 定，是最便宜的时刻（改一个还不存在的历史值不需要迁移）。
     *
     * <p>10 分钟这个数字**不是拍的**：需求 `09` §4.3 的「图片传输」一行写死了
     * 「先落 MinIO，传 **10 分钟预签名 URL**」—— 那条口径服务的正是同一条链路
     * （图片先落桶，再由 VL 取图 / 前端渲染缩略图）。
     *
     * <p>⚠️ 它同时要服务两个消费者：前端 {@code <img src>}（立即）与将来 VL 的取图
     * （`T-512`）。**两处都读同一个对象**，所以这里只有一个值；若哪天 VL 需要更长窗口，
     * 那是"VL 那一路单独延长"，不是把这个值调大让前端也跟着变长。
     */
    public static final int CHAT_ATTACHMENT_SECONDS = 600;

    /**
     * 文档下载 / 预览：**10 分钟**（单位分钟）。`T-614`/`T-613` 新增。
     *
     * <h3>这就是 `T-O06` 步 4 判据 5 挂了三批的那个「收窄对象」</h3>
     * <p>`O6` 步 4 原文「预签名 URL 收窄：TTL 从当前值降到 5 分钟」在 `S4-E2` 挂起，
     * 理由是**它要收窄的对象根本不存在**（那时全仓只有头像 7 天、审计导出 24h，
     * 都不是文档下载）。`S5-M08-C` 复核后仍挂（第三处预签名是问答附件，也不是文档下载）。
     * 本批（`S7-M06-E`）**才创建** `GET /doc/download-url/{docId}` 与 `/doc/{id}/preview-url`
     * —— 收窄的对象至此第一次出现，所以判据 5 在本批**合并验收**（`S4-E2` 计划文件同步回填）。
     *
     * <h3>为什么是 10 分钟，而不是 `O6` 建议的 5 分钟</h3>
     * <p>取 10 不是拍的：需求 `10` §14 的两行端点表逐字写死
     * 「`/doc/{id}/preview-url` → **10 分钟有效**」「`/doc/download-url/{docId}` 🚩」——
     * 需求已经把这个面的口径定在 10 分钟。而 `O6` 的「5 分钟」是**通用建议值**，
     * 不是针对文档下载量过的数。两者冲突时，**门禁口径（需求）优先于优化建议**。
     *
     * <p>它与审计/运营导出的 24h **不同链路**，所以收得短是对的：下载 / 预览是
     * **同步点开、立即用**（用户点"下载"→浏览器立刻打开 URL），不走"异步任务完成→
     * 通知中心→用户第二天点开"那条链路。10 分钟足够一次点击到下载开始，
     * 而 URL 一旦泄露，短 TTL 把"别人拿它绕过密级/知识库权限"的窗口压到最小
     * —— 那正是 `O6` 步 4 收窄的**原意**（下载 URL 直连 MinIO，绕过应用层 ACL）。
     *
     * <p>⚠️ 已知边界：超大文件 10 分钟可能下不完 ⇒ "下载中 URL 过期"。需求未提续签，
     * 登记为遗留（本批 §9）。真要支持要么延长本值、要么加"重新签发"入口，
     * 而不是把所有下载 URL 都放长（那就把泄露窗口又放大了）。
     */
    public static final int DOC_DOWNLOAD_MINUTES = 10;

    /** 文档预览：同 {@link #DOC_DOWNLOAD_MINUTES}（需求 `10` §14 line 151 写死 10 分钟）。
     *  与下载同一条理由（同步点开、立即用），单列出来只为让"预览"与"下载"各自可独立调整。 */
    public static final int DOC_PREVIEW_MINUTES = 10;

    /**
     * 下载记录清单导出件：**24 小时**（单位小时）。`T-615` 新增。
     *
     * <p>⚠️ **它与上面两个 {@code DOC_*_MINUTES} 不是同一档**，别看到"文档"就当同类合并：
     * 那两个是**同步点击**（用户点下载 → 浏览器立刻打开 URL），而这个是
     * **异步任务 + 通知中心**（`POST /doc/export-list` → 生成 CSV → 通知里给地址）——
     * 用户很可能第二天才点开那条通知。
     *
     * <p>⇒ 它跟的是 {@link #AUDIT_EXPORT_HOURS} 那一条链路与那一条理由，故取同一个值。
     * 敏感面在四个值里**最轻**（"我自己下过什么"），若哪天要收窄，收的也应该是它。
     */
    public static final int DOC_EXPORT_HOURS = 24;
}
